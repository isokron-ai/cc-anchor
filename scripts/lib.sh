# ═══════════════════ 0.4.0: kronicle-lite retraction push + pulse ═══════════════════
#
# Track B (agent-memory-bench, T1): agents that orient at session start never
# re-orient before a deploy (0/36 pull runs); pushing new retractions into the
# context after each tool call fixed it (10/10). Two hooks share this code:
#
#   PostToolUse (push)   after every tool call, fetch the retractions that
#                        landed since this session's cursor and inject them
#                        as additionalContext; advance + persist the cursor.
#   PreToolUse (pulse)   before a world-changing Bash command (config
#                        `pulse_match`), same fetch; an unreconciled semantic
#                        safety/behavioral retraction denies the command
#                        (config `pulse_mode`: deny | warn).
#
# Per-session runtime files under $CC_RUN/push/<sid8>.*:
#   cfg      "<data dir>\n<cli path>" — resolved once per session
#   off      kronicle-lite not configured / no CLI: the hooks are inert
#   cursor   full kronicle-lite cursor (actor cc-anchor-<sid8>)
#   seq      chain head seq the cursor was issued at
#   stamp    mtime gate: touched just BEFORE each read of the chain. While
#            kronicle-lite.db and its -wal are older than the stamp nothing
#            can have changed, so the hot path costs two builtin `-ot` tests
#            and no process. A change makes the next call run a read-only
#            `orient --focus pulse` (head seq) and, only if the head moved,
#            `orient --cursor C --focus retractions`.
#   pending  blocking retractions the push delivered on the LAST tool result.
#            Any later tool call clears it (the agent had a turn to act on
#            it); a world-changing command issued straight after the push is
#            denied first.
#   fail     epoch of the last CLI failure (back-off: retry after 60 s)
#   integrity  "<seq>\x1f<problem>" while kronicle-lite reports integrity.ok
#            false (corrupt / tampered store); intwarned: the problem this
#            agent was last warned about (once per distinct problem)
#   down     consecutive push/pulse calls that could not read the store (CLI
#            missing from the cache, timeout, error, non-JSON); downwarned:
#            the one "feed offline" advisory of this outage was given
#
# Fail-open everywhere: a missing CLI, a slow or broken store, a timeout
# (config `push_timeout` s, default 3, per CLI call) never blocks a tool call
# and never prints anything but valid hook JSON; one log line says why.

CC_KL_B=""; CC_KL_S=""; CC_KL_SID=""; CC_KL_AGENT=""; CC_KL_DD=""; CC_KL_BIN=""; CC_KL_ACTOR=""; CC_KL_ACTOR_SRC=""; CC_KL_FAILED=0; CC_KL_XFAIL=0
KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0; KL_SEQ=""

cc_epoch_now_var() {  # NAME — epoch seconds without a fork on bash >= 4.2
  local __t
  # Tests drive the clock explicitly (second-boundary logic) instead of
  # depending on wall-clock luck.
  if [[ "${CC_ANCHOR_TEST_NOW:-}" =~ ^[0-9]+$ ]]; then printf -v "$1" '%s' "$CC_ANCHOR_TEST_NOW"; return 0; fi
  printf -v __t '%(%s)T' -1 2>/dev/null || __t=""
  [[ "$__t" =~ ^[0-9]+$ ]] || __t="$(date +%s)"
  printf -v "$1" '%s' "$__t"
}

# cc_kl_session <session_id> [agent_id] — file prefixes (builtins only).
#   CC_KL_S  per session: cfg / off / fail (the CLI and its health are shared)
#   CC_KL_B  per AGENT:   cursor / seq / stamp / pending. The main agent is
#            "<sid8>", a subagent "<sid8>.a-<agent_id>" (or "a-h<hash of the
#            whole id>" when it is long or not filename-safe). Each subagent has its
#            own cursor, seeded from the main agent's at SubagentStart, so a
#            retraction one agent consumed still reaches its siblings and the
#            parent (each exactly once).
cc_kl_session() {
  local s="${1:-nosession}" a="${2:-}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  CC_KL_SID="${s:-nosession}"
  CC_KL_S="$CC_RUN/push/$CC_KL_SID"
  # agent_id is an opaque string (docs: "agent-abc123", "def456"). Keep it
  # whole when it is filename-safe and short — distinct ids then get distinct
  # files with no process; otherwise a hash of the WHOLE id (never a prefix
  # of it: two subagents must not share a cursor).
  if [[ -z "$a" ]]; then CC_KL_AGENT=""
  elif (( ${#a} <= 64 )) && [[ "$a" =~ ^[A-Za-z0-9_-]+$ ]]; then CC_KL_AGENT="$a"
  else CC_KL_AGENT="h$(cc_hash "$a")"; fi
  if [[ -n "$CC_KL_AGENT" ]]; then CC_KL_B="$CC_KL_S.a-$CC_KL_AGENT"; else CC_KL_B="$CC_KL_S"; fi
}

# cc_payload_agent <payload> — the hook's agent_id ("" in the main agent).
# jq only when the payload mentions agent_id at all (subagents), and read
# from the top level: a tool_input may carry its own "agent_id".
cc_payload_agent() {
  [[ "$1" == *'"agent_id"'* ]] || return 0
  jq -r '.agent_id // "" | tostring' <<<"$1" 2>/dev/null || true
}

# cc_kl_seed — start a subagent's cursor where its parent's is (copy), so
# everything the parent has not consumed yet reaches the subagent too.
# Falls back to the head when the parent has no cursor. Main agent: init.
cc_kl_seed() {
  [[ -n "$CC_KL_AGENT" && ! -e "$CC_KL_B.live" ]] && cc_kl_inherit
  if [[ -n "$CC_KL_AGENT" && -s "$CC_KL_S.cursor" ]]; then
    cp -f "$CC_KL_S.cursor" "$CC_KL_B.cursor.$$" 2>/dev/null && mv -f "$CC_KL_B.cursor.$$" "$CC_KL_B.cursor" || return 1
    if [[ -s "$CC_KL_S.seq" ]]; then cp -f "$CC_KL_S.seq" "$CC_KL_B.seq" 2>/dev/null || true; fi
    rm -f "$CC_KL_B.stamp" 2>/dev/null
    return 0
  fi
  cc_kl_init
}

# cc_kl_forget — drop a stopped subagent's cursor files (not its actors).
cc_kl_forget() {
  [[ -n "$CC_KL_AGENT" ]] || return 0
  rm -f "$CC_KL_B.cursor" "$CC_KL_B.seq" "$CC_KL_B.stamp" "$CC_KL_B.pending" "$CC_KL_B.parked" "$CC_KL_B.intwarned" "$CC_KL_B.oneliner" \
        "$CC_KL_B.klpend" "$CC_KL_B.pendcalls" "$CC_KL_B.reminded" "$CC_KL_B.wcattempt" "$CC_KL_B".xp-* 2>/dev/null || true
  # 0.5.2: its reconciliation ledger is parked (<S>.stopped/a-<id>.*), still
  # fed while it is stopped, and taken back if the same agent_id resumes.
  cc_kl_ledger_park
  # The actors it read as (<B>.actors, and 0.5.0's <B>.actor) stay: a resumed
  # subagent comes back with the same agent_id, and what it read before the
  # stop is still pending for it (0.5.1, H2-10).
}

# Data dir of the kronicle-lite store the agent's MCP server uses.
# CC_ANCHOR_KRONICLE_DATA_DIR > config kronicle_data_dir > the kronicle-lite
# MCP server's --data-dir DIR / --data-dir=DIR / env KRONICLE_LITE_DATA_DIR in
# .mcp.json or ~/.claude.json (see CC_KL_SERVERS_JQ) > $KRONICLE_LITE_DATA_DIR
# > "" (the CLI's own default, ~/.kronicle-lite).
cc_kl_data_dir() {
  local v f phys
  v="${CC_ANCHOR_KRONICLE_DATA_DIR:-}"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  v="$(cc_cfg_raw kronicle_data_dir)"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  phys="$(cc_root_phys)"
  while IFS= read -r f; do
    [[ -s "$f" ]] || continue
    v="$(jq -r --arg root "$CC_ROOT" --arg phys "$phys" "$CC_KL_SERVERS_JQ"' klopt("--data-dir"; "KRONICLE_LITE_DATA_DIR")' "$f" 2>/dev/null)"
    [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  done < <(cc_cfg_files)
  printf '%s' "${KRONICLE_LITE_DATA_DIR:-}"
}

# The actor whose reads count for kronicle-lite's `pending` (0.8.0): the
# agent's MCP server actor. CC_ANCHOR_KRONICLE_ACTOR > config kronicle_actor
# > the kronicle-lite server's --actor ID / --actor=ID / env
# KRONICLE_LITE_ACTOR in .mcp.json or ~/.claude.json > $KRONICLE_LITE_ACTOR >
# "local-agent" (the server default). Prints "<actor>\x1f<named|default>":
# default = found nowhere, a guess (0.5.1, L2-04: the gate then also keeps
# the retraction rule and says how to name the actor).
cc_kl_actor_detect() {
  local v f phys
  v="${CC_ANCHOR_KRONICLE_ACTOR:-}"; [[ -n "$v" ]] && { printf '%s\x1fnamed' "$v"; return 0; }
  v="$(cc_cfg_raw kronicle_actor)"; [[ -n "$v" ]] && { printf '%s\x1fnamed' "$v"; return 0; }
  phys="$(cc_root_phys)"
  while IFS= read -r f; do
    [[ -s "$f" ]] || continue
    v="$(jq -r --arg root "$CC_ROOT" --arg phys "$phys" "$CC_KL_SERVERS_JQ"' klopt("--actor"; "KRONICLE_LITE_ACTOR")' "$f" 2>/dev/null)"
    [[ -n "$v" ]] && { printf '%s\x1fnamed' "$v"; return 0; }
  done < <(cc_cfg_files)
  if [[ -n "${KRONICLE_LITE_ACTOR:-}" ]]; then printf '%s\x1fnamed' "$KRONICLE_LITE_ACTOR"; else printf 'local-agent\x1fdefault'; fi
}

# The actor `orient --pending-actor` reports on: the session's configured
# server actor. Every OTHER actor_id this agent has passed to an MCP tool is
# in <B>.actors and checked too (cc_kl_extra_pending): the gate is on the
# union, and naming another actor never clears what this one has pending
# (0.5.1, H2-03c). Builtins only.
cc_kl_agent_actor() { printf '%s' "$CC_KL_ACTOR"; }

# 0.5.1 (L2-04): what to tell the agent when the server actor is a guess.
cc_kl_actor_note() {
  printf '%s' "cc-anchor does not know which kronicle-lite actor your MCP server reads as — none is named in .mcp.json or ~/.claude.json (a --mcp-config file or a plugin server is not visible to hooks) — so it checks \`${CC_KL_ACTOR}\` plus every new retraction. Set CC_ANCHOR_KRONICLE_ACTOR (or kronicle_actor in .claude/cc-anchor.json) to the server's --actor for the full pending gate."
}

# cc_kl_learn_actor <PostToolUse payload> — remember an actor_id the agent
# passed in tool_input of ANY MCP tool (the kronicle-lite server may be
# registered under any key, or as a plugin: mcp__<anything>__*). Adding an
# id that is not a kronicle-lite actor costs one `pending` read that finds
# nothing; missing one would let reads under it go unchecked (H2-03d).
cc_kl_learn_actor() {
  [[ "$1" == *'"actor_id"'* && "$1" =~ \"tool_name\":[[:space:]]*\"mcp__ ]] || return 0
  local na; na="$(jq -r '.tool_input.actor_id // empty | tostring | gsub("[[:cntrl:]]"; "")' <<<"$1" 2>/dev/null)"
  [[ -n "$na" && "$na" != "$CC_KL_ACTOR" ]] || return 0
  if [[ -s "$CC_KL_B.actors" ]] && grep -Fxq -- "$na" "$CC_KL_B.actors" 2>/dev/null; then return 0; fi
  printf '%s\n' "$na" >> "$CC_KL_B.actors" 2>/dev/null || return 0
  cc_log "push: agent ${CC_KL_AGENT:-main} used kronicle actor ${na:0:64}; gated on it as well as ${CC_KL_ACTOR}"
}

# File for an extra actor's last `pending` read (same format as <B>.klpend).
cc_kl_xp_file() {
  if (( ${#1} <= 64 )) && [[ "$1" =~ ^[A-Za-z0-9_.-]+$ ]]; then printf '%s' "$CC_KL_B.xp-$1"
  else printf '%s' "$CC_KL_B.xp-h$(cc_hash "$1")"; fi
}

# cc_kl_extra_pending — refresh the pending reads of the extra actors that
# have none since the store last changed (cc_kl_pending_note drops them on
# every fresh briefing), all in parallel, each bounded by push_timeout.
# A read that fails leaves no file: that actor counts as unknown (the CLI is
# failing; logged), the last known answer of the others still stands.
cc_kl_extra_pending() {
  # A session started under 0.5.0 kept one learned actor in <B>.actor.
  if [[ -s "$CC_KL_B.actor" ]]; then cat "$CC_KL_B.actor" >> "$CC_KL_B.actors" 2>/dev/null && rm -f "$CC_KL_B.actor"; fi
  [[ -s "$CC_KL_B.actors" && -e "$CC_KL_S.klcap" ]] || return 0
  local a f to pcwd n=0; to="$(cc_cfg_raw push_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=3
  local -a todo=() bg=()
  while IFS= read -r a; do
    [[ -n "$a" ]] || continue
    f="$(cc_kl_xp_file "$a")"
    [[ -s "$f" ]] || todo+=("$a")
  done < "$CC_KL_B.actors"
  (( ${#todo[@]} > 0 )) || return 0
  pcwd="$(cd "$CC_ROOT" 2>/dev/null && pwd -P)"
  for a in "${todo[@]}"; do
    f="$(cc_kl_xp_file "$a")"
    (
      args=(pending --actor "$a" --json --cwd "${pcwd:-$CC_ROOT}")
      [[ -n "$CC_KL_DD" ]] && args+=(--data-dir "$CC_KL_DD")
      if [[ "$CC_KL_BIN" == *.js || "$CC_KL_BIN" == *.mjs ]]; then cc_with_timeout "$to" node "$CC_KL_BIN" "${args[@]}" > "$f.raw.$$" 2>/dev/null
      else cc_with_timeout "$to" "$CC_KL_BIN" "${args[@]}" > "$f.raw.$$" 2>/dev/null; fi
    ) &
    bg+=($!)
  done
  wait "${bg[@]}" 2>/dev/null
  for a in "${todo[@]}"; do
    f="$(cc_kl_xp_file "$a")"
    local r="" raw=""; [[ -s "$f.raw.$$" ]] && raw="$(cat "$f.raw.$$")" && r="$(cc_kl_pending_fmt "$raw")"
    rm -f "$f.raw.$$" 2>/dev/null
    if [[ -n "$r" && "$r" != nocap ]]; then
      printf '%s\n' "$r" > "$f" 2>/dev/null
      # 0.5.2: pending for an actor_id agents passed themselves: owed by the
      # agents that used it (known), not by every agent.
      [[ "${r%%$'\x1f'*}" =~ ^[1-9][0-9]*$ ]] && cc_kl_ledger_feed "$raw" "$a"
    else n=$((n + 1)); fi
  done
  CC_KL_XFAIL=$n
  (( n > 0 )) && cc_log_once kl_xperr "pulse: kronicle-lite pending could not be read for ${n} extra actor(s); last known answers stand"
  return 0
}

# cc_kl_enabled — 0 when the push/pulse should run for this session (and
# CC_KL_DD / CC_KL_BIN are set). Switch `push`: on | off | auto (default:
# on when kronicle-lite is configured for the project). Resolved once per
# session into <sid8>.cfg / <sid8>.off; env CC_ANCHOR_PUSH=0 always wins.
cc_kl_enabled() {
  [[ "${CC_ANCHOR_KRONICLE:-}" == 0 ]] && return 1
  local sw; sw="$(cc_cfg_raw push)"
  case "$sw" in 0|false|no|off) return 1;; esac
  if [[ -s "$CC_KL_S.cfg" ]]; then
    { IFS= read -r CC_KL_DD; IFS= read -r CC_KL_BIN; IFS= read -r CC_KL_ACTOR; IFS= read -r CC_KL_ACTOR_SRC; } < "$CC_KL_S.cfg"
    [[ -n "$CC_KL_ACTOR" ]] || IFS=$'\x1f' read -r CC_KL_ACTOR CC_KL_ACTOR_SRC <<<"$(cc_kl_actor_detect)"
    [[ -n "$CC_KL_ACTOR_SRC" ]] || CC_KL_ACTOR_SRC=named
    [[ -n "$CC_KL_BIN" ]] && return 0
  fi
  [[ -e "$CC_KL_S.off" ]] && return 1
  mkdir -p "$CC_RUN/push" 2>/dev/null || return 1
  case "$sw" in
    1|true|yes|on) ;;
    *) cc_kronicle_configured || { : > "$CC_KL_S.off"; return 1; };;
  esac
  CC_KL_BIN="$(cc_find_cli kronicle-lite)" || {
    : > "$CC_KL_S.off"
    cc_log_once kl_nobin "push: kronicle-lite is configured but its CLI was not found (PATH, plugin cache, CC_ANCHOR_KRONICLE_LITE_BIN); retraction push/pulse off"
    return 1; }
  CC_KL_DD="$(cc_kl_data_dir)"
  IFS=$'\x1f' read -r CC_KL_ACTOR CC_KL_ACTOR_SRC <<<"$(cc_kl_actor_detect)"
  printf '%s\n%s\n%s\n%s\n' "$CC_KL_DD" "$CC_KL_BIN" "$CC_KL_ACTOR" "$CC_KL_ACTOR_SRC" > "$CC_KL_S.cfg" 2>/dev/null || return 1
  return 0
}

# cc_kl_orient ARGS… — `kronicle-lite orient --json` for this session's actor,
# bounded by push_timeout. Prints the JSON; non-zero on failure / timeout.
cc_kl_orient() {
  local to; to="$(cc_cfg_raw push_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=3
  # --pending-actor (kronicle-lite >= 0.8.0; older versions ignore it): the
  # briefing then carries pending[] for the AGENT's reads, not the hook's.
  # --cwd as a PHYSICAL path: kronicle-lite (>= 0.7.0) scopes documents by a
  # project key derived from the working directory, and a `put` from the MCP
  # server or the CLI records process.cwd(), which resolves symlinks (macOS:
  # /var -> /private/var). A literal $CLAUDE_PROJECT_DIR through a symlink
  # would name a different project and hide every retraction.
  local pcwd; pcwd="$(cd "$CC_ROOT" 2>/dev/null && pwd -P)"
  local -a a=(orient --json --actor "cc-anchor-$CC_KL_SID" --pending-actor "$(cc_kl_agent_actor)" --cwd "${pcwd:-$CC_ROOT}")
  [[ -n "$CC_KL_DD" ]] && a+=(--data-dir "$CC_KL_DD")
  # stderr is kept (last call only) so a failure can be told apart: a corrupt
  # store is not "offline" (cc_kl_fail; 0.5.1, L2-03).
  if [[ "$CC_KL_BIN" == *.js || "$CC_KL_BIN" == *.mjs ]]; then cc_with_timeout "$to" node "$CC_KL_BIN" "${a[@]}" "$@" 2>"$CC_KL_S.stderr"
  else cc_with_timeout "$to" "$CC_KL_BIN" "${a[@]}" "$@" 2>"$CC_KL_S.stderr"; fi
}

# Unavailable bookkeeping: every push/pulse call that could not read the
# store (failure, or inside the back-off) counts; any successful read resets.
cc_kl_down() {
  local n=0; [[ -s "$CC_KL_S.down" ]] && IFS= read -r n < "$CC_KL_S.down"
  [[ "$n" =~ ^[0-9]+$ ]] || n=0
  printf '%s\n' "$((n + 1))" > "$CC_KL_S.down" 2>/dev/null || true
}
cc_kl_up() {
  [[ -e "$CC_KL_S.unavailwarned" ]] && rm -f "$CC_KL_S.unavailwarned" 2>/dev/null
  [[ -e "$CC_KL_S.down" ]] || return 0
  rm -f "$CC_KL_S.down" "$CC_KL_S.downwarned" 2>/dev/null
  cc_log "push: kronicle-lite readable again; retraction feed back online"
}

# cc_kl_integrity_note <seq> <problem> | ok — record what the last briefing
# said about store integrity.
cc_kl_integrity_note() {
  if [[ "$1" == ok ]]; then
    [[ -e "$CC_KL_S.integrity" ]] || return 0
    rm -f "$CC_KL_S.integrity" 2>/dev/null
    cc_log "push: kronicle-lite integrity ok again"
    return 0
  fi
  local cur=""; [[ -s "$CC_KL_S.integrity" ]] && IFS= read -r cur < "$CC_KL_S.integrity"
  [[ "$cur" == "$1"$'\x1f'"$2" ]] && return 0
  printf '%s\x1f%s\n' "$1" "$2" > "$CC_KL_S.integrity" 2>/dev/null || true
  cc_log "push: kronicle-lite INTEGRITY FAILURE at seq $1: $2"
}

# Parse one orient JSON's integrity (any focus): sets the note when ok:false.
# Echoes nothing; returns 0 when the store reported a failure.
cc_kl_integrity_from() {
  local line
  line="$(jq -r 'if (.integrity | type) == "object" and .integrity.ok == false
    then "fail\u001f\(.integrity.seq // .integrity.at_seq // .integrity.first_bad_seq // "?")\u001f\(.integrity.problem // .integrity.error // "integrity check failed" | tostring | gsub("\\s+"; " ") | .[0:240])"
    elif (.integrity | type) == "object" and .integrity.ok == true then "ok" else "" end' <<<"$1" 2>/dev/null)"
  case "$line" in
    fail*) local s p; IFS=$'\x1f' read -r _ s p <<<"$line"; cc_kl_integrity_note "$s" "$p"; return 0;;
    ok) cc_kl_integrity_note ok;;
  esac
  return 1
}

# cc_kl_pending_note <orient JSON> — record what kronicle-lite (>= 0.8.0)
# says is still pending for this agent's actor:
#   <S>.klcap / <S>.klnocap  this kronicle-lite reports `pending` / does not
#   <B>.klpend               "count\x1fhidden\x1factor\x1fslugs" then one
#                            "- …" line per item (at most 6)
# Builtins + one jq. A briefing without pending_count (kronicle-lite <= 0.7.0)
# switches the gate back to the retraction-since-last-look logic.
# cc_kl_pending_fmt <orient or `pending --json` output> prints that text, or
# "nocap" for a briefing without pending_count.
cc_kl_pending_fmt() {
  jq -r --arg mode fmt -f "$CC_LIB_DIR/owed.jq" <<<"$1" 2>/dev/null
}

cc_kl_pending_note() {
  local r
  r="$(cc_kl_pending_fmt "$1")" || return 0
  if [[ "$r" == nocap ]]; then
    [[ -e "$CC_KL_S.klcap" ]] && rm -f "$CC_KL_S.klcap" 2>/dev/null
    [[ -e "$CC_KL_B.klpend" ]] && rm -f "$CC_KL_B.klpend" 2>/dev/null
    [[ -e "$CC_KL_S.klnocap" ]] || : > "$CC_KL_S.klnocap"
    return 0
  fi
  [[ -n "$r" ]] || return 0
  [[ -e "$CC_KL_S.klcap" ]] || { : > "$CC_KL_S.klcap"; rm -f "$CC_KL_S.klnocap" 2>/dev/null; }
  printf '%s\n' "$r" > "$CC_KL_B.klpend.$$" 2>/dev/null && mv -f "$CC_KL_B.klpend.$$" "$CC_KL_B.klpend"
  # A fresh briefing means the store may have changed: the extra actors'
  # answers are re-read the next time the gate needs them.
  [[ -s "$CC_KL_B.actors" ]] && rm -f "$CC_KL_B".xp-* 2>/dev/null
  # 0.5.2 (L2-05): pending for the configured actor — shared by every agent
  # of the session, so whose read it was is unknown: every agent owes it.
  # Retractions in the briefing move the agents' owed items forward.
  local n="${r%%$'\x1f'*}"
  if [[ "$n" =~ ^[1-9][0-9]*$ || "$1" == *'"successor_block_id"'* ]]; then cc_kl_ledger_feed "$1"; fi
  return 0
}

# Pending count for this agent from the last briefing ("" = unknown).
cc_kl_pending_count() {
  [[ -s "$CC_KL_B.klpend" ]] || return 0
  local l=""; IFS= read -r l < "$CC_KL_B.klpend"
  l="${l%%$'\x1f'*}"
  [[ "$l" =~ ^[0-9]+$ ]] && printf '%s' "$l"
}

# Force a fresh pending read (the pulse, when it has none for this agent).
cc_kl_pending_refresh() {
  local out rc
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  (( rc == 0 )) && [[ -n "$out" ]] || return 1
  cc_kl_pending_note "$out"
}

cc_kl_fail() {  # rc — remember a failure (60 s back-off), log once per hour
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$CC_KL_S.fail" 2>/dev/null || true
  CC_KL_FAILED=1
  # 0.5.1 (L2-03): a store that cannot be opened because it is damaged
  # (exit 77, SQLite CORRUPT / NOTADB, "malformed", "not a database") is an
  # integrity failure, not an outage: the push warns at once (top priority)
  # and the pulse lets only read-only calls run — instead of failing open
  # and advising "offline" after push_offline_after calls.
  local err=""; [[ -s "$CC_KL_S.stderr" ]] && err="$(head -c 400 "$CC_KL_S.stderr" 2>/dev/null | tr '\n' ' ')"
  if [[ "$1" == 77 ]] || [[ "$err" =~ (SQLITE_CORRUPT|SQLITE_NOTADB|[Mm]alformed|not a database|integrity|hash mismatch|corrupt) ]]; then
    cc_kl_integrity_note "?" "the store cannot be read (kronicle-lite exit $1: ${err:0:200})"
    cc_log_once kl_corrupt "push: kronicle-lite store looks damaged (exit $1); treating it as an integrity failure"
    return 0
  fi
  cc_kl_down
  if [[ "$1" == 124 ]]; then cc_log_once kl_timeout "push: kronicle-lite orient timed out (push_timeout); failing open"
  else cc_log_once kl_err "push: kronicle-lite orient failed (exit $1); failing open"; fi
}

cc_kl_backoff() {  # 0 while inside the 60 s failure back-off
  [[ -s "$CC_KL_S.fail" ]] || return 1
  local t now; IFS= read -r t < "$CC_KL_S.fail" || t=0
  cc_epoch_now_var now
  if [[ "$t" =~ ^[0-9]+$ ]] && (( now - t < 60 )); then CC_KL_FAILED=1; cc_kl_down; return 0; fi
  return 1
}

# cc_kl_init — start this session's cursor at the current head (silent).
cc_kl_init() {  # [strict] — the pulse reads even inside the back-off
  [[ "${1:-}" == strict ]] || { cc_kl_backoff && return 1; }
  local pre="$CC_KL_B.stamp.$$" out rc cur seq
  cc_kl_prestamp "$pre" || return 1
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  IFS=$'\x1f' read -r cur seq < <(jq -r '[(.cursor // ""), ((.head.seq // "") | tostring)] | join("\u001f")' <<<"$out" 2>/dev/null)
  if [[ -z "$cur" ]]; then rm -f "$pre"; cc_kl_fail 2; return 1; fi
  cc_kl_pending_note "$out"
  printf '%s\n' "$cur" > "$CC_KL_B.cursor" && printf '%s\n' "$seq" > "$CC_KL_B.seq" && mv -f "$pre" "$CC_KL_B.stamp"
  rm -f "$pre" "$CC_KL_S.fail" 2>/dev/null
  cc_kl_up
  return 0
}

# The stamp is touched just BEFORE a read of the chain and holds that
# moment's epoch second, for the tie rule below.
cc_kl_prestamp() {  # <file>
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$1" 2>/dev/null
}

# Compare two files' mtimes the way `test` sees them: echo older|newer|tie.
# bash 3.2 (macOS /bin/bash) compares whole seconds; bash >= 5.1 uses the
# filesystem's precision. CC_ANCHOR_TEST_MTIME_SECONDS=1 forces the 1-second
# view on any host (tests), via date -r (GNU and BSD).
cc_mtime_cmp() {  # <a> <b>
  if [[ "${CC_ANCHOR_TEST_MTIME_SECONDS:-0}" == 1 ]]; then
    local x y; x="$(date -r "$1" +%s 2>/dev/null)"; y="$(date -r "$2" +%s 2>/dev/null)"
    if (( x < y )); then echo older; elif (( x > y )); then echo newer; else echo tie; fi
    return 0
  fi
  if [[ "$1" -ot "$2" ]]; then echo older; elif [[ "$1" -nt "$2" ]]; then echo newer; else echo tie; fi
}

# cc_kl_unchanged [strict] — 0 when the store cannot have changed since the
# stamp. Hot path: builtin `-ot` tests, no process.
#   older than the stamp  -> unchanged
#   newer than the stamp  -> changed
#   a tie at `test`'s granularity (1 s with bash 3.2, the macOS default):
#     the store was written in the same second as our last read. Re-reading
#     on every tie made every tool call in that second spawn kronicle-lite
#     (macOS CI). Instead one `find -newer` settles it at the filesystem's
#     own precision (ns on APFS / ext4): stamp newer -> unchanged, store
#     newer -> changed. Only a tie even there (1-s filesystem, or one kernel
#     tick) stays ambiguous: the pulse (`strict`, before a world-changing
#     command) re-reads; the push re-reads once the clock has left the
#     stamp's second, so a store write costs at most one extra read and a
#     write landing in that same second right after our read reaches the
#     agent at its next tool call in a later second.
cc_kl_unchanged() {
  [[ -e "$CC_KL_B.stamp" ]] || return 1
  local db="${CC_KL_DD:-${KRONICLE_LITE_DATA_DIR:-$HOME/.kronicle-lite}}/kronicle-lite.db" f c
  local -a tied=()
  [[ -e "$db" ]] || return 1
  for f in "$db" "$db-wal"; do
    [[ -e "$f" ]] || continue
    if [[ "${CC_ANCHOR_TEST_MTIME_SECONDS:-0}" != 1 ]]; then
      [[ "$f" -ot "$CC_KL_B.stamp" ]] && continue
      [[ "$f" -nt "$CC_KL_B.stamp" ]] && return 1
    else
      c="$(cc_mtime_cmp "$f" "$CC_KL_B.stamp")"
      [[ "$c" == older ]] && continue
      [[ "$c" == newer ]] && return 1
    fi
    tied+=("$f")
  done
  (( ${#tied[@]} == 0 )) && return 0
  local equal=0
  for f in "${tied[@]}"; do
    if [[ -n "$(find "$CC_KL_B.stamp" -newer "$f" -print 2>/dev/null)" ]]; then continue
    elif [[ -n "$(find "$f" -newer "$CC_KL_B.stamp" -print 2>/dev/null)" ]]; then return 1
    else equal=1; fi
  done
  (( equal )) || return 0
  [[ "${1:-}" == strict ]] && return 1
  local t="" now; IFS= read -r t < "$CC_KL_B.stamp" || true
  [[ "$t" =~ ^[0-9]+$ ]] || return 1
  cc_epoch_now_var now
  (( now <= t ))
}

# cc_kl_fetch — new retractions since this session's cursor. Returns 0 when
# the head moved and the retractions were fetched (KL_SHOWN may still be 0),
# 1 when nothing changed, the CLI failed (fail open) or no cursor existed yet.
# Sets KL_BODY ("- …" lines), KL_SHOWN, KL_BLOCK, KL_COS, KL_SEQ.
cc_kl_fetch() {  # [strict] — see cc_kl_unchanged
  KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0; KL_SEQ=""
  # 0.5.2: a subagent first seen alive (no SubagentStart, or started under an
  # older cc-anchor) inherits what the session's agents still owe.
  [[ -n "$CC_KL_AGENT" && ! -e "$CC_KL_B.live" ]] && cc_kl_inherit
  if [[ ! -s "$CC_KL_B.cursor" ]]; then
    # Main agent without a cursor: start at the head (nothing is "new" yet).
    # Subagent without one (no SubagentStart seen): seed from the parent and
    # go on to fetch, so what the parent has not consumed reaches it too.
    if [[ -z "$CC_KL_AGENT" || ! -s "$CC_KL_S.cursor" ]]; then cc_kl_init "${1:-}" || CC_KL_FAILED=1; return 1; fi
    cc_kl_seed || { CC_KL_FAILED=1; return 1; }
  fi
  # Parked at a corrupt head and the store has since been found ok (by any
  # agent of the session): re-read from the unmoved cursor.
  if [[ -e "$CC_KL_B.parked" && ! -e "$CC_KL_S.integrity" ]]; then rm -f "$CC_KL_B.parked" "$CC_KL_B.seq" "$CC_KL_B.stamp" 2>/dev/null; fi
  cc_kl_unchanged "${1:-}" && return 1
  # The push honours the 60 s back-off after a failure; the pulse (strict)
  # never does: a cached answer from before the store changed is not an
  # answer (0.5.1, H2-11).
  [[ "${1:-}" == strict ]] || { cc_kl_backoff && return 1; }
  local pre="$CC_KL_B.stamp.$$" out rc seq stored="" cur=""
  cc_kl_prestamp "$pre" || return 1
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  seq="$(jq -r '.head.seq // empty' <<<"$out" 2>/dev/null)"
  if [[ -z "$seq" ]]; then rm -f "$pre"; cc_kl_fail 3; return 1; fi
  cc_kl_integrity_from "$out" || true
  cc_kl_pending_note "$out"
  [[ -s "$CC_KL_B.seq" ]] && IFS= read -r stored < "$CC_KL_B.seq"
  if [[ -n "$seq" && "$seq" == "$stored" ]]; then
    # 0.5.1 (L2-02): the store changed but the head did not move — a
    # rewrite of a stored block or event (projection-only tamper) does
    # exactly that, and `--focus pulse` carries no integrity verdict. Check
    # with the read-only `verify-chain` (the retractions focus would answer
    # too, but it writes the store and every call would re-read).
    mv -f "$pre" "$CC_KL_B.stamp"; cc_kl_up
    cc_kl_verify
    return 1
  fi
  IFS= read -r cur < "$CC_KL_B.cursor"
  out="$(cc_kl_orient --cursor "$cur" --focus retractions)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  cc_kl_pending_note "$out"
  local sc=0; cc_on push_cosmetic 0 && sc=1
  local parsed
  parsed="$(jq -r --arg show_cosmetic "$sc" -f "$CC_LIB_DIR/retractions.jq" <<<"$out" 2>/dev/null)" || { rm -f "$pre"; cc_kl_fail 3; return 1; }
  local ncur counts rest integ
  ncur="${parsed%%$'\n'*}"; rest="${parsed#*$'\n'}"
  KL_SEQ="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  counts="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  integ="${rest%%$'\n'*}"
  if [[ "$rest" == *$'\n'* ]]; then KL_BODY="${rest#*$'\n'}"; else KL_BODY=""; fi
  if [[ "$integ" == fail* ]]; then
    # The store says it is corrupt: deliver no retractions from it and keep
    # the cursor where it was (after a repair they are re-read from there);
    # remember the head so the next calls do not re-read it each time.
    local iseq iprob; IFS=$'\x1f' read -r _ iseq iprob <<<"$integ"
    cc_kl_integrity_note "$iseq" "$iprob"
    printf '%s\n' "$KL_SEQ" > "$CC_KL_B.seq"
    : > "$CC_KL_B.parked"
    KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0
    mv -f "$pre" "$CC_KL_B.stamp"; rm -f "$CC_KL_S.fail" 2>/dev/null
    cc_kl_up
    return 0
  fi
  cc_kl_integrity_note ok
  read -r KL_SHOWN KL_BLOCK KL_COS <<<"$counts"
  [[ "$KL_SHOWN" =~ ^[0-9]+$ ]] || KL_SHOWN=0
  [[ "$KL_BLOCK" =~ ^[0-9]+$ ]] || KL_BLOCK=0
  [[ "$KL_COS" =~ ^[0-9]+$ ]] || KL_COS=0
  if [[ -n "$ncur" ]]; then
    printf '%s\n' "$ncur" > "$CC_KL_B.cursor.$$" && mv -f "$CC_KL_B.cursor.$$" "$CC_KL_B.cursor"
    printf '%s\n' "$KL_SEQ" > "$CC_KL_B.seq"
  fi
  mv -f "$pre" "$CC_KL_B.stamp"
  rm -f "$CC_KL_S.fail" 2>/dev/null
  cc_kl_up
  return 0
}

# cc_kl_verify — `kronicle-lite verify-chain` (read-only), bounded by
# push_timeout: exit 1 notes an integrity failure (first mismatch, or the
# summary line), exit 0 clears one, anything else (slow on a big store, an
# old CLI) is inconclusive and changes nothing (logged once).
cc_kl_verify() {
  local to out rc prob; to="$(cc_cfg_raw push_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=3
  local -a a=(verify-chain); [[ -n "$CC_KL_DD" ]] && a+=(--data-dir "$CC_KL_DD")
  if [[ "$CC_KL_BIN" == *.js || "$CC_KL_BIN" == *.mjs ]]; then out="$(cc_with_timeout "$to" node "$CC_KL_BIN" "${a[@]}" 2>"$CC_KL_S.stderr")"; rc=$?
  else out="$(cc_with_timeout "$to" "$CC_KL_BIN" "${a[@]}" 2>"$CC_KL_S.stderr")"; rc=$?; fi
  case "$rc" in
    0) [[ "$out" == *'"ok": true'* || "$out" == *'"ok":true'* ]] && cc_kl_integrity_note ok;;
    1)
      prob="$(jq -r 'if (.projection.mismatches // []) | length > 0 then (.projection.mismatches[0] | "\(.table // "?") \(.key // "?") \(.field // ""): \(.detail // "projection mismatch")")
        elif .first_mismatch != null then "chain mismatch at \(.first_mismatch | if type == "object" then (.seq // tostring) else tostring end)"
        else "verify-chain failed" end | gsub("\\s+"; " ") | .[0:240]' <<<"$out" 2>/dev/null)"
      [[ -n "$prob" ]] || prob="$(head -c 240 "$CC_KL_S.stderr" 2>/dev/null | tr '\n' ' ')"
      cc_kl_integrity_note "?" "${prob:-verify-chain failed}: the store does not match its chain";;
    *) cc_log_once kl_verify "push: kronicle-lite verify-chain inconclusive (exit $rc); integrity not re-checked";;
  esac
  return 0
}

cc_kl_integrity_text() {
  local s="?" p="integrity check failed"
  [[ -s "$CC_KL_S.integrity" ]] && IFS=$'\x1f' read -r s p < "$CC_KL_S.integrity"
  local at=""; [[ "$s" =~ ^[0-9]+$ ]] && at=" at seq ${s}"
  printf '%s' "cc-anchor: kronicle-lite STORE INTEGRITY FAILURE${at}: ${p}. The chain is corrupt or was tampered with: do not act on runbooks, notes or anything else recalled from kronicle-lite until it is resolved (kronicle-lite verify-chain / doctor; tell the operator). Meanwhile the cc-anchor pulse lets only read-only Bash commands run (unless pulse_mode is warn)."
}

# cc_kl_integrity_recheck — re-read integrity now (bypassing the mtime gate):
# 0 while the store still reports a failure (or cannot be read), 1 once ok.
cc_kl_integrity_recheck() {
  local cur="" out rc
  [[ -s "$CC_KL_B.cursor" ]] && IFS= read -r cur < "$CC_KL_B.cursor"
  local -a c=(); [[ -n "$cur" ]] && c=(--cursor "$cur")
  out="$(cc_kl_orient ${c[@]+"${c[@]}"} --focus retractions)"; rc=$?
  (( rc == 0 )) && [[ -n "$out" ]] || return 0
  cc_kl_pending_note "$out"
  cc_kl_integrity_from "$out" && return 0
  [[ -e "$CC_KL_S.integrity" ]] && return 0
  # Repaired: forget the head we parked at, so the next fetch re-reads the
  # retractions since the (unmoved) cursor.
  rm -f "$CC_KL_B.seq" "$CC_KL_B.stamp" "$CC_KL_B.intwarned" "$CC_KL_B.parked" 2>/dev/null
  return 1
}

# cc_kl_push <PostToolUse payload> — sets CC_KL_CONTEXT (empty: say nothing).
CC_KL_CONTEXT=""
cc_kl_push() {
  local payload="$1" sid=""
  CC_KL_CONTEXT=""
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_kl_session "$sid" "$(cc_payload_agent "$payload")"
  [[ -e "$CC_KL_S.off" ]] && return 0
  cc_kl_enabled || return 0
  # The agent named a kronicle-lite actor in an MCP tool call: the gate
  # checks that actor too, from now on (union, per agent; 0.5.1).
  cc_kl_learn_actor "$payload"
  # The agent got a tool call in since the last push: what it was told is no
  # longer "unacted on".
  [[ -e "$CC_KL_B.pending" ]] && rm -f "$CC_KL_B.pending"
  cc_kl_fetch || true
  cc_kl_ledger_retry || true
  # 0.5.2 (L2-05): this agent's own re-reads clear its ledger.
  cc_kl_observe "$payload"
  # Top priority: a store that says it is corrupt (once per distinct problem).
  local warn=""
  if [[ -s "$CC_KL_S.integrity" ]]; then
    local key="" seen=""; IFS= read -r key < "$CC_KL_S.integrity"
    [[ -s "$CC_KL_B.intwarned" ]] && IFS= read -r seen < "$CC_KL_B.intwarned"
    if [[ "$key" != "$seen" ]]; then
      printf '%s\n' "$key" > "$CC_KL_B.intwarned" 2>/dev/null || true
      warn="$(cc_kl_integrity_text)"
    fi
  fi
  # A feed that has been unreadable for push_offline_after consecutive calls.
  local after n=0; after="$(cc_cfg_raw push_offline_after)"; [[ "$after" =~ ^[0-9]+$ ]] || after=20
  [[ -s "$CC_KL_S.down" ]] && IFS= read -r n < "$CC_KL_S.down"
  if [[ "$n" =~ ^[0-9]+$ ]] && (( after > 0 && n >= after )) && [[ ! -e "$CC_KL_S.downwarned" ]]; then
    : > "$CC_KL_S.downwarned"
    cc_log "push: retraction feed offline for ${n} consecutive calls; advised the agent once"
    warn="${warn:+$warn

}cc-anchor: the kronicle-lite retraction feed has been offline for ${n} consecutive tool calls (the CLI is missing, failing or timing out; see .claude/cc-anchor/log). Changes to runbooks and notes are NOT being pushed to you right now: re-read the source (get_system_state with your cursor, recall) yourself before any world-changing command."
  fi
  # Delivered is not reconciled (kronicle-lite >= 0.8.0 `pending`): a change
  # the agent still has not re-read push_reminder_after (15) tool calls after
  # it became pending, with no world-changing command attempted meanwhile
  # (the pulse would have shown it), gets ONE reminder line.
  local pc; pc="$(cc_kl_pending_count)"
  if [[ "$pc" =~ ^[0-9]+$ ]] && (( pc > 0 )); then
    local k=0 ra; [[ -s "$CC_KL_B.pendcalls" ]] && IFS= read -r k < "$CC_KL_B.pendcalls"
    [[ "$k" =~ ^[0-9]+$ ]] || k=0; k=$((k + 1)); printf '%s\n' "$k" > "$CC_KL_B.pendcalls"
    ra="$(cc_cfg_raw push_reminder_after)"; [[ "$ra" =~ ^[0-9]+$ ]] || ra=15
    if (( ra > 0 && k >= ra )) && [[ ! -e "$CC_KL_B.reminded" && ! -e "$CC_KL_B.wcattempt" ]]; then
      : > "$CC_KL_B.reminded"
      local head="" slugs="" act=""; IFS= read -r head < "$CC_KL_B.klpend"
      IFS=$'\x1f' read -r _ _ act slugs <<<"$head"
      cc_log "push: pending reminder (${pc} item(s), actor ${act}) after ${k} tool calls"
      warn="${warn:+$warn

}cc-anchor: reminder — ${pc} kronicle-lite change(s) you relied on are still not re-read at their current version (${slugs:-see kronicle-lite pending --actor ${act}}). Receiving them earlier does not count: re-read (recall, or kronicle://docs/<slug>) before acting on them."
    fi
  elif [[ -e "$CC_KL_B.pendcalls" || -e "$CC_KL_B.reminded" || -e "$CC_KL_B.wcattempt" ]]; then
    rm -f "$CC_KL_B.pendcalls" "$CC_KL_B.reminded" "$CC_KL_B.wcattempt" 2>/dev/null
  fi
  if (( KL_SHOWN == 0 )); then CC_KL_CONTEXT="$warn"; return 0; fi
  CC_KL_CONTEXT="${warn:+$warn

}cc-anchor: kronicle-lite changed while you were working — ${KL_SHOWN} retraction(s) since your last check (head seq ${KL_SEQ}). Anything you read before this may be stale:
${KL_BODY}
Re-read the affected document (recall, or get_system_state with your cursor) and use the current text before you act on it."
  if (( KL_COS > 0 )) && ! cc_on push_cosmetic 0; then CC_KL_CONTEXT="${CC_KL_CONTEXT} (${KL_COS} cosmetic edit(s) not shown.)"; fi
  # L2-04: said once per session, with the first change it matters for.
  if [[ "$CC_KL_ACTOR_SRC" == default && ! -e "$CC_KL_S.actorwarned" ]]; then
    : > "$CC_KL_S.actorwarned" 2>/dev/null || true
    CC_KL_CONTEXT="${CC_KL_CONTEXT}
$(cc_kl_actor_note)"
  fi
  (( KL_BLOCK > 0 )) && printf '%s\n' "$KL_BODY" > "$CC_KL_B.pending"
  cc_log "push: ${KL_SHOWN} retraction(s) (${KL_BLOCK} blocking, ${KL_COS} cosmetic) at seq ${KL_SEQ}"
  return 0
}

# ═══════════════════ 0.5.2: per-agent reconciliation ledger (L2-05) ═══════════════════
#
# kronicle-lite's `pending` is per actor, and every agent of a Claude Code
# session normally reads as the same actor (the MCP server's --actor). So one
# subagent's re-read cleared the pending gate for all of them, and a subagent
# started after the coordinator had consumed the push got neither the push
# nor a deny. The gate now also holds each AGENT to its own re-reads:
#
#   <B>.owed   changes this agent has not re-read itself (JSONL; scripts/owed.jq)
#   <B>.done   keys it re-read (a later feed never re-adds them)
#   <B>.reads  kronicle-lite blocks / "doc:<slug>" it was SEEN reading
#   <B>.fed    the last feed applied (identical feeds are skipped)
#   <B>.live   (subagents) seen alive: SubagentStart, or its first hook
#   <S>.stopped/a-<agent>.*   a stopped subagent's ledger, parked; it is still
#              fed, and taken back if the same agent_id resumes
#   <S>.lock   one lock (mkdir) for every write to another agent's ledger
#
# Who owes what (fail closed whenever attribution is uncertain):
#   * pending for the configured actor: every agent of the session (the
#     actor is shared, so whose read it was is unknown);
#   * pending for an actor_id an agent passed on its MCP calls: the agents
#     that used it;
#   * a blocking retraction of a block or document an agent was seen reading
#     (recall hit, document read, `kronicle-lite get`): that agent — this
#     also catches a change written by another agent AS the shared actor,
#     which kronicle-lite counts as that actor's read, so `pending` never
#     lists it;
#   * a subagent first seen alive inherits what every agent of the session
#     still owes, and what they were seen reading (its parent is not named
#     in SubagentStart, and anything it was told may be stale).
# What clears it: only that agent's own tool result showing the current
# version (scripts/owed.jq, mode clear). A later change of the same block
# replaces the owed item with the newer one. Inert on kronicle-lite <= 0.7.0
# (no `pending`: the 0.4.0 retraction rule decides there, as before).

CC_KL_LOCKED=0

# 0.5.3: the lock is a directory holding its owner's pid. It is taken over
# only when that owner is gone (or a zombie); a live owner's lock is never
# broken, however old (12 parallel agents broke a live lock by age in 0.5.2
# and then wrote unlocked). After 3 s it gives up: the caller skips its
# update and fails closed (cc_kl_ledger_feed queues it, the gate denies
# until it is applied). flock(1) is not used: macOS has none.
cc_kl_alive() { [[ "$1" =~ ^[0-9]+$ ]] && kill -0 "$1" 2>/dev/null && [[ "$(ps -o stat= -p "$1" 2>/dev/null)" != *Z* ]]; }
cc_kl_lock() {
  local l="$CC_KL_S.lock" i=0 owner
  while ! mkdir "$l" 2>/dev/null; do
    i=$((i + 1))
    if (( i % 10 == 0 )); then
      owner=""; [[ -s "$l/pid" ]] && IFS= read -r owner < "$l/pid"
      # no pid yet: the owner is between mkdir and its write; wait for it
      if [[ -n "$owner" ]] && ! cc_kl_alive "$owner"; then
        rm -f "$l/pid" 2>/dev/null; rmdir "$l" 2>/dev/null
        cc_log "push: took over the ledger lock of exited pid ${owner}"
        continue
      fi
    fi
    if (( i > 150 )); then cc_log "push: ledger lock busy for 3 s (held by pid ${owner:-?}); update skipped, gate stays closed"; return 1; fi
    sleep 0.02 2>/dev/null || sleep 1
  done
  printf '%s\n' "$$" > "$l/pid" 2>/dev/null
  CC_KL_LOCKED=1
}
cc_kl_unlock() {
  (( CC_KL_LOCKED )) || return 0
  rm -f "$CC_KL_S.lock/pid" 2>/dev/null; rmdir "$CC_KL_S.lock" 2>/dev/null; CC_KL_LOCKED=0
}

# 0.5.3: <prefix>.owed is only ever written through cc_kl_owed_put, which
# also writes <prefix>.owed.sum ("<lines> <cksum>"). cc_kl_owed_ok fails when
# the two disagree (the ledger was truncated or edited outside cc-anchor) or
# a line is not a ledger item: the gate then fails closed.
cc_kl_owed_put() {  # <prefix> <content without trailing newline | "">
  local h="$1" n=0 sum="-"
  if [[ -n "$2" ]]; then
    printf '%s\n' "$2" > "$h.owed.$$" 2>/dev/null && mv -f "$h.owed.$$" "$h.owed" || return 1
    n="$(grep -c . "$h.owed" 2>/dev/null)"; sum="$(cksum < "$h.owed" 2>/dev/null)"; sum="${sum%% *}"
  else rm -f "$h.owed" 2>/dev/null; fi
  printf '%s %s\n' "$n" "$sum" > "$h.owed.sum.$$" 2>/dev/null && mv -f "$h.owed.sum.$$" "$h.owed.sum"
}
cc_kl_owed_ok() {  # <prefix>
  local h="$1" n s cur
  [[ -e "$h.owed.sum" ]] || { [[ -e "$h.owed" ]] && return 1; return 0; }
  read -r n s < "$h.owed.sum" 2>/dev/null || return 1
  if [[ "$n" == 0 ]]; then [[ ! -s "$h.owed" ]]; return; fi
  [[ -s "$h.owed" ]] || return 1
  cur="$(cksum < "$h.owed" 2>/dev/null)"; [[ "${cur%% *}" == "$s" ]] || return 1
  [[ "$(grep -c . "$h.owed" 2>/dev/null)" == "$n" ]]
}
cc_kl_owed_move() {  # <from prefix> <to prefix> — append, keep both sums right
  local all
  all="$( { cc_kl_slurp "$2.owed"; [[ -s "$2.owed" ]] && echo; cc_kl_slurp "$1.owed"; } | grep . )"
  cc_kl_owed_put "$2" "$all"; cc_kl_owed_put "$1" ""
  rm -f "$1.owed.sum" 2>/dev/null
}

# Every ledger of the session, one prefix per line: the main agent, the
# subagents seen alive, the parked ledgers of stopped ones.
cc_kl_holders() {
  local f
  printf '%s\n' "$CC_KL_S"
  for f in "$CC_KL_S".a-*.live; do [[ -e "$f" ]] && printf '%s\n' "${f%.live}"; done
  for f in "$CC_KL_S.stopped"/a-*.done; do [[ -e "$f" ]] && printf '%s\n' "${f%.done}"; done
  return 0
}

cc_kl_slurp() {  # <file> — its content ("" when missing), no fork for the read
  [[ -s "$1" ]] || return 0
  local __c; __c="$(< "$1")" 2>/dev/null && printf '%s' "$__c"
}

cc_kl_who() {  # <prefix> — "the main agent" / "subagent <id>"
  local h="${1##*/}"; h="${h#"$CC_KL_SID"}"; h="${h#.}"
  if [[ -z "$h" ]]; then printf 'the main agent'; else printf 'subagent %s' "${h#a-}"; fi
}

# cc_kl_ledger_feed <orient / pending JSON> [actor] — fold the pending items
# and the retraction steps into every ledger (with [actor]: only those of the
# agents that passed that actor_id). No-op on kronicle-lite <= 0.7.0.
cc_kl_ledger_feed() {
  [[ -e "$CC_KL_S.klcap" ]] || return 0
  local feed only="${2:-}" h ap out prev n0 n1
  feed="$(jq -r --arg mode feed -f "$CC_LIB_DIR/owed.jq" <<<"$1" 2>/dev/null)" || return 0
  [[ "$feed" == '{"p":[],"r":[]}' || -z "$feed" ]] && return 0
  local haspend=1; [[ "$feed" == '{"p":[],'* ]] && haspend=0
  if ! cc_kl_lock; then
    # fail closed: keep the input; the gate denies until it is applied
    printf '%s\n%s' "$only" "$1" > "$CC_KL_S.feedq.$$" 2>/dev/null && mv -f "$CC_KL_S.feedq.$$" "$CC_KL_S.feedq"
    return 0
  fi
  while IFS= read -r h; do
    [[ -n "$h" ]] || continue
    if [[ -n "$only" ]]; then
      ap="${h/.stopped\//.}.actors"
      if [[ ! -s "$ap" ]] || ! grep -Fxq -- "$only" "$ap" 2>/dev/null; then continue; fi
    fi
    # Steps only matter to a ledger that owes something or was seen reading.
    (( haspend )) || [[ -s "$h.owed" || -s "$h.reads" ]] || continue
    prev=""; [[ -s "$h.fed" ]] && prev="$(< "$h.fed")"
    [[ "$prev" == "$feed" ]] && continue
    out="$(jq -nr --arg mode reg --arg feed "$feed" --arg owed "$(cc_kl_slurp "$h.owed")" \
            --arg "done" "$(cc_kl_slurp "$h.done")" --arg reads "$(cc_kl_slurp "$h.reads")" -f "$CC_LIB_DIR/owed.jq" 2>/dev/null)" || continue
    n0=0; [[ -s "$h.owed" ]] && n0="$(grep -c . "$h.owed" 2>/dev/null)"
    cc_kl_owed_put "$h" "$out" || continue
    printf '%s' "$feed" > "$h.fed" 2>/dev/null
    n1=0; [[ -n "$out" ]] && n1="$(grep -c . <<<"$out")"
    [[ "$n0" != "$n1" ]] && cc_log "push: ledger: $(cc_kl_who "$h") owes ${n1} re-read(s) (was ${n0})${only:+ (actor ${only:0:64})}"
  done < <(cc_kl_holders)
  rm -f "$CC_KL_S.feedq" 2>/dev/null
  cc_kl_unlock
  return 0
}

# cc_kl_ledger_retry — a feed skipped on a busy lock is applied now (pulse
# and push call it first). 1 while it is still queued (the gate denies).
cc_kl_ledger_retry() {
  [[ -e "$CC_KL_S.feedq" ]] || return 0
  local only raw
  { IFS= read -r only; raw="$(cat)"; } < "$CC_KL_S.feedq" 2>/dev/null
  cc_kl_ledger_feed "$raw" "$only"
  [[ ! -e "$CC_KL_S.feedq" ]]
}

# cc_kl_inherit — a subagent seen alive for the first time takes what every
# agent of the session still owes and was seen reading (its parent is not
# named, and anything it was handed may be stale), plus its own parked
# ledger when its agent_id resumes after a stop.
cc_kl_inherit() {
  [[ -n "$CC_KL_AGENT" ]] || return 0
  mkdir -p "$CC_RUN/push" 2>/dev/null || return 0
  local P="$CC_KL_S.stopped/a-$CC_KL_AGENT" h x owed="" reads="" out n
  # busy: not inherited yet, so not .live — retried at the next hook; the
  # gate denies this agent meanwhile (<B>.busy)
  cc_kl_lock || { : > "$CC_KL_B.busy" 2>/dev/null; return 0; }
  [[ -e "$P.owed" || -e "$P.owed.sum" ]] && cc_kl_owed_move "$P" "$CC_KL_B"
  for x in "done" reads; do
    if [[ -e "$P.$x" ]]; then cat "$P.$x" >> "$CC_KL_B.$x" 2>/dev/null; rm -f "$P.$x" 2>/dev/null; fi
  done
  rm -f "$P.fed" 2>/dev/null
  while IFS= read -r h; do
    [[ -n "$h" && "$h" != "$CC_KL_B" ]] || continue
    [[ -s "$h.owed" ]] && owed="${owed}$(< "$h.owed")"$'\n'
    [[ -s "$h.reads" ]] && reads="${reads}$(< "$h.reads")"$'\n'
  done < <(cc_kl_holders)
  if [[ -n "$owed" || -s "$CC_KL_B.owed" ]]; then
    out="$(jq -nr --arg mode merge --arg owed "$(cc_kl_slurp "$CC_KL_B.owed")"$'\n'"$owed" --arg "done" "$(cc_kl_slurp "$CC_KL_B.done")" -f "$CC_LIB_DIR/owed.jq" 2>/dev/null)" || out=""
    if [[ -n "$out" ]]; then
      cc_kl_owed_put "$CC_KL_B" "$out"
      n="$(grep -c . <<<"$out")"
      cc_log "push: ledger: $(cc_kl_who "$CC_KL_B") starts owing ${n} re-read(s) the session's agents still owe"
    fi
  fi
  if [[ -n "$reads" ]]; then
    { cc_kl_slurp "$CC_KL_B.reads"; [[ -s "$CC_KL_B.reads" ]] && echo; printf '%s' "$reads"; } | grep . | sort -u > "$CC_KL_B.reads.$$" 2>/dev/null \
      && mv -f "$CC_KL_B.reads.$$" "$CC_KL_B.reads"
  fi
  [[ -e "$CC_KL_B.owed.sum" ]] || cc_kl_owed_put "$CC_KL_B" "$(cc_kl_slurp "$CC_KL_B.owed")"
  : > "$CC_KL_B.live" 2>/dev/null
  rm -f "$CC_KL_B.busy" 2>/dev/null
  cc_kl_unlock
  return 0
}

# cc_kl_ledger_park — SubagentStop: move the ledger aside (not deleted).
cc_kl_ledger_park() {
  [[ -n "$CC_KL_AGENT" ]] || return 0
  [[ -e "$CC_KL_B.live" || -e "$CC_KL_B.owed" || -e "$CC_KL_B.done" || -e "$CC_KL_B.reads" ]] || return 0
  local P="$CC_KL_S.stopped/a-$CC_KL_AGENT" x
  mkdir -p "$CC_KL_S.stopped" 2>/dev/null || return 0
  # busy: the ledger stays where it is (a resume finds it in place)
  cc_kl_lock || return 0
  cc_kl_owed_move "$CC_KL_B" "$P"
  for x in "done" reads; do
    if [[ -e "$CC_KL_B.$x" ]]; then cat "$CC_KL_B.$x" >> "$P.$x" 2>/dev/null; rm -f "$CC_KL_B.$x" 2>/dev/null; fi
    [[ -e "$P.$x" ]] || : > "$P.$x" 2>/dev/null
  done
  rm -f "$CC_KL_B.live" "$CC_KL_B.fed" 2>/dev/null
  cc_kl_unlock
}

# cc_kl_observe <PostToolUse payload> — what this tool result shows the agent
# read: owed items it re-read at the current version clear (for this agent
# only), and the blocks / documents it read are remembered. The jq runs only
# when the result can carry kronicle-lite content (a block_id, a
# kronicle://docs/ resource, a Bash `kronicle-lite get`). A re-read through
# a plain `kronicle-lite get` in Bash clears only when kronicle-lite itself
# confirms it (read-only `pending --actor`: the item is no longer pending
# for that actor, i.e. it recorded a read of the current version); if that
# check fails, nothing clears. On a busy lock nothing clears either.
cc_kl_observe() {
  [[ -e "$CC_KL_S.klcap" ]] || return 0
  local p="$1"
  if [[ "$p" == *'block_id'* || "$p" == *'kronicle://docs/'* ]]; then :
  elif [[ "$p" =~ \"tool_name\":[[:space:]]*\"Bash\" && "$p" =~ (kronicle-lite|cli\.m?js)[\"\']?[[:space:]]+get ]]; then :
  else return 0; fi
  local out held=0 tag v owed="" cleared="" forget="" reads="" vb="" k actor rd item still
  if [[ -s "$CC_KL_B.owed" ]]; then cc_kl_lock || return 0; held=1; fi
  out="$(jq -r --arg mode clear --arg owed "$(cc_kl_slurp "$CC_KL_B.owed")" -f "$CC_LIB_DIR/owed.jq" <<<"$p" 2>/dev/null)" || out=""
  while IFS=$'\t' read -r tag v; do
    case "$tag" in
      O) owed="${owed}${v}"$'\n';; C) cleared="${cleared}${v}"$'\n';;
      B) vb="${vb}${v}"$'\n';;
      F) forget="${forget}${v}"$'\n';; R) reads="${reads}${v}"$'\n';;
    esac
  done <<<"$out"
  if [[ -n "$vb" ]]; then
    IFS=$'\x1f' read -r _ actor _ <<<"$vb"; [[ -n "$actor" ]] || actor="$CC_KL_ACTOR"
    still="$(cc_kl_still_pending "$actor")" || still="*"
    while IFS=$'\x1f' read -r k _ rd item; do
      [[ -n "$k" ]] || continue
      if [[ "$still" == "*" ]] || grep -Fxq -- "$k" <<<"$still"; then owed="${owed}${item}"$'\n'
      else cleared="${cleared}${k}"$'\n'; [[ -n "$rd" ]] && forget="${forget}${rd}"$'\n'; fi
    done <<<"$vb"
    [[ "$still" == "*" ]] && cc_log "push: ledger: could not ask kronicle-lite to confirm a re-read by $(cc_kl_who "$CC_KL_B"); nothing cleared"
  fi
  if [[ -n "$cleared" ]]; then
    cc_kl_owed_put "$CC_KL_B" "${owed%$'\n'}"
    printf '%s' "$cleared" >> "$CC_KL_B.done" 2>/dev/null
    cc_log "push: ledger: $(cc_kl_who "$CC_KL_B") re-read $(grep -c . <<<"$cleared") change(s) at the current version; $(grep -c . <<<"$owed") still owed"
  fi
  (( held )) && cc_kl_unlock
  if [[ -n "$reads" || -n "$forget" ]]; then
    { cc_kl_slurp "$CC_KL_B.reads"; echo; printf '%s' "$reads"; } | grep . | { if [[ -n "$forget" ]]; then grep -Fvx -- "$forget"; else cat; fi; } | sort -u > "$CC_KL_B.reads.$$" 2>/dev/null
    mv -f "$CC_KL_B.reads.$$" "$CC_KL_B.reads" 2>/dev/null
  fi
  return 0
}

# cc_kl_still_pending <actor> — the ledger keys kronicle-lite still lists as
# pending for <actor> (read-only `pending --json`), one per line; status 1
# when it cannot be read.
cc_kl_still_pending() {
  local to raw pcwd; to="$(cc_cfg_raw push_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=3
  pcwd="$(cd "$CC_ROOT" 2>/dev/null && pwd -P)"
  local -a a=(pending --actor "$1" --json --cwd "${pcwd:-$CC_ROOT}")
  [[ -n "$CC_KL_DD" ]] && a+=(--data-dir "$CC_KL_DD")
  if [[ "$CC_KL_BIN" == *.js || "$CC_KL_BIN" == *.mjs ]]; then raw="$(cc_with_timeout "$to" node "$CC_KL_BIN" "${a[@]}" 2>/dev/null)" || return 1
  else raw="$(cc_with_timeout "$to" "$CC_KL_BIN" "${a[@]}" 2>/dev/null)" || return 1; fi
  jq -er '(.pending // error("no pending")) | .[] | if (.current.block_id // null) != null then "c:\(.current.block_id)" else "t:\(.read.block_id):\(.seq // "?")" end' <<<"$raw" 2>/dev/null
  local rc=$?; (( rc == 0 || rc == 4 )) || [[ "$raw" == *'"pending": []'* || "$raw" == *'"pending":[]'* ]]
}

# ═══════════════════ 0.5.0: Bash claimed-path guard (sea-lite) ═══════════════════
#
# The Edit/Write scope guard never sees `sed -i`, redirects, formatters or
# codegen run through Bash, and sea-lite's pre-commit guard only fires at
# commit time. So after every Bash call: did it change a path inside a live
# sea-lite claim held by ANOTHER session? If so, say so right away
# (PostToolUse additionalContext) naming the path, the holder, the ticket and
# the expiry. Advisory: the change already happened; the agent undoes it or
# coordinates.
#
#   PreToolUse(Bash)  (pulse.sh) writes <run>/bashguard/<sid8>.pre.<tool_use_id>
#                     — one stamp PER CALL, so overlapping Bash calls of one
#                     session (parallel tool calls, subagents) don't clobber
#                     each other; its mtime is "this call began".
#   PostToolUse(Bash) that call's stamp + the claims other sessions hold (a
#                     cached `sea-lite board --json`; refreshed when older than
#                     bash_guard_ttl s, when the sea-lite store file changed
#                     since the cache was filled, or after any sea_* result).
#                     No foreign claim => no process. Otherwise ONE
#                     `find <claimed paths> -newer|-cnewer <stamp>`: change time
#                     as well as modification time, so mtime-preserving writes
#                     (cp -p / -a, tar -x, mv over a file, touch -r) count. A
#                     find that times out falls back to `git status` over the
#                     claimed paths. A hit costs one `git status` to drop
#                     git-ignored output before warning.
#
# Switch `bash_guard`: on | off | auto (default: on when this project has seen
# sea-lite claims or sea-lite is configured), resolved once per session.
# Fail-open: no CLI / timeout / bad output => no warning, one log line.

CC_BG_CONTEXT=""

cc_bg_session() {  # <session_id> — CC_BG_B (per-session prefix), CC_BG_D (dir)
  local s="${1:-nosession}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  CC_BG_D="$CC_RUN/bashguard"; CC_BG_B="$CC_BG_D/${s:-nosession}"
}

cc_bg_enabled() {
  [[ -e "$CC_BG_B.on" ]] && return 0
  [[ -e "$CC_BG_B.off" ]] && return 1
  mkdir -p "$CC_BG_D" 2>/dev/null || return 1
  case "$(cc_cfg_raw bash_guard)" in
    0|false|no|off) : > "$CC_BG_B.off"; return 1;;
    1|true|yes|on) ;;
    *) if [[ ! -s "$CC_CLAIMS" ]] && ! cc_sea_configured; then : > "$CC_BG_B.off"; return 1; fi;;
  esac
  if ! cc_find_cli sea-lite >/dev/null; then
    : > "$CC_BG_B.off"; : > "$CC_BG_B.nobin"
    cc_log_once bg_nobin "bash_guard: sea-lite CLI not found; Bash-changed paths are not checked against claims"
    return 1
  fi
  : > "$CC_BG_B.on"
}

# 0 when the Bash payload's command starts background work: a `&` that is
# not part of && |& >& &>, or nohup / setsid / disown. jq only when the
# payload contains one of them at all.
cc_bg_starts_job() {
  [[ "$1" == *'&'* || "$1" =~ (nohup|setsid|disown) ]] || return 1
  local bc; bc="$(jq -r '.tool_input.command // "" | tostring' <<<"$1" 2>/dev/null)"
  [[ "$bc" =~ (^|[^\&\|\>])\&([^\&\>]|$) || "$bc" =~ (^|[^A-Za-z0-9_-])(nohup|setsid|disown)([^A-Za-z0-9_-]|$) ]]
}

cc_bg_tid() {  # <payload> — sanitized tool_use_id ("notid" when absent: one
  # stamp per session then, so overlapping id-less calls share it)
  local t=""
  [[ "$1" =~ \"tool_use_id\":[[:space:]]*\"([^\"]*)\" ]] && t="${BASH_REMATCH[1]}"
  t="${t//[^A-Za-z0-9_-]/}"; t="${t:0:64}"; printf '%s' "${t:-notid}"
}

# PreToolUse(Bash): stamp the start of THIS call (one builtin write).
cc_bg_prestamp() {  # <payload>
  local payload="$1" sid="" tid
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_bg_session "$sid"
  [[ -e "$CC_BG_B.off" ]] && return 0
  tid="$(cc_bg_tid "$payload")"
  [[ -n "$tid" ]] || return 0
  [[ -d "$CC_BG_D" ]] || mkdir -p "$CC_BG_D" 2>/dev/null || return 0
  : > "$CC_BG_B.pre.$tid" 2>/dev/null || true
  if cc_bg_starts_job "$payload"; then : > "$CC_BG_B.bgjob.$tid" 2>/dev/null || true; fi
  # 0.5.1 (H2-18): which claimed paths exist right now (builtins), so a path
  # removed through its parent (rm -rf src, mv src x, a checkout) is known
  # to have existed before this call.
  if [[ -s "$CC_BG_D/claims.tsv" ]]; then
    local ses path rest; local -a ex=()
    while IFS=$'\x1f' read -r ses path rest; do [[ -n "$path" && -e "$path" ]] && ex+=("$path"); done < "$CC_BG_D/claims.tsv"
    if (( ${#ex[@]} > 0 )); then printf '%s\n' "${ex[@]}" > "$CC_BG_B.present.$tid" 2>/dev/null || true; fi
  fi
}

# 0.5.1 (H2-20/H2-22): when sea-lite cannot answer, the claim guards fail
# open — and say so ONCE per outage per session (the Edit/Write scope guard
# and the Bash guard share the latch <run>/sea-advised.<sid8>), like the
# kronicle-lite "feed offline" advisory. cc_sea_advise <session> <why> sets
# CC_SEA_ADVICE and returns 0 when the agent should be told now.
CC_SEA_ADVICE=""
cc_sea_advise() {
  local s="${1:-nosession}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  local latch="$CC_RUN/sea-advised.${s:-nosession}"
  CC_SEA_ADVICE=""
  [[ -e "$latch" ]] && return 1
  cc_ensure_dirs || return 1
  : > "$latch" 2>/dev/null || return 1
  cc_log "sea-lite unavailable (${2}); advised the agent once"
  CC_SEA_ADVICE="cc-anchor: sea-lite is not answering right now (${2}). The claim guards are NOT checking your edits against other agents' sea-lite claims until it does (the Edit/Write scope guard allows every edit; the Bash guard uses the last claims it saw, if any). Check \`sea-lite board\` yourself before editing files another agent may hold."
  return 0
}
cc_sea_recovered() {
  local s="${1:-nosession}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  [[ -e "$CC_RUN/sea-advised.${s:-nosession}" ]] || return 0
  rm -f "$CC_RUN/sea-advised.${s:-nosession}" 2>/dev/null
  cc_log "sea-lite answering again; claim guards checking"
}

cc_bg_seadb() { printf '%s' "${CC_ANCHOR_SEA_DATA_DIR:-${KRONICLE_LITE_DATA_DIR:-$HOME/.kronicle-lite}}/kronicle-lite.db"; }

# Refresh <dir>/claims.tsv from `sea-lite board --json`: one line per live
# claimed scope: session \x1f absolute path \x1f holder \x1f ticket \x1f title \x1f expires
cc_bg_refresh() {
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$CC_BG_D/claims.at" 2>/dev/null || return 1
  # Drop per-call stamps whose PostToolUse never came (older than 10 min).
  find "$CC_BG_D" -maxdepth 1 \( -name '*.pre.*' -o -name '*.present.*' -o -name '*.bgjob.*' \) -mmin +10 -exec rm -f {} + 2>/dev/null || true
  local bin to out rc ttl
  bin="$(cc_find_cli sea-lite)" || { printf '127\n' > "$CC_BG_D/claims.degraded"; return 1; }
  to="$(cc_cfg_raw scope_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=4
  local -a args=(board --json)
  [[ -n "${CC_ANCHOR_SEA_DATA_DIR:-}" ]] && args+=(--data-dir "$CC_ANCHOR_SEA_DATA_DIR")
  if [[ "$bin" == *.js || "$bin" == *.mjs ]]; then out="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout "$to" node "$bin" "${args[@]}" 2>/dev/null)"; rc=$?
  else out="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout "$to" "$bin" "${args[@]}" 2>/dev/null)"; rc=$?; fi
  if (( rc != 0 )) || [[ -z "$out" ]] || [[ "$out" != *'"tickets"'* ]]; then
    # 0.5.1 (H2-20): one slow or failed board call no longer empties the
    # cache for bash_guard_ttl. The last good claims stay in use (their age
    # is in claims.good), the next refresh is tried after 5 s, and the agent
    # is told once per outage (cc_sea_advise) that the guard is degraded.
    # With no good claims to fall back on, the next call retries at once.
    ttl="$(cc_cfg_raw bash_guard_ttl)"; [[ "$ttl" =~ ^[0-9]+$ ]] || ttl=30
    local wait=5; [[ -e "$CC_BG_D/claims.good" ]] || wait=1   # nothing to fall back on: retry at once
    printf '%s\n' "$((now - ttl + wait))" > "$CC_BG_D/claims.at" 2>/dev/null || true
    printf '%s\n' "$rc" > "$CC_BG_D/claims.degraded" 2>/dev/null || true
    cc_log_once bg_board "bash_guard: sea-lite board failed (exit $rc); using the last claims seen, retrying in 5 s"
    return 1
  fi
  # The board call itself may write the store: stamp the cache AFTER it, so
  # only a later write (a new claim by anyone) looks newer.
  : > "$CC_BG_D/claims.stamp" 2>/dev/null || true
  rm -f "$CC_BG_D/claims.degraded" 2>/dev/null
  printf '%s\n' "$now" > "$CC_BG_D/claims.good" 2>/dev/null || true
  # sea-lite reports the project by its physical path (macOS: /private/var/…
  # for /var/…); rewrite it to this hook's spelling of the root so finds and
  # messages use the paths the agent sees.
  local phys; phys="$(cd "$CC_ROOT" 2>/dev/null && pwd -P)"
  jq -r --arg root "$CC_ROOT" --arg phys "${phys:-$CC_ROOT}" '.tickets[]? | select(.claim != null) | . as $t | .claim as $c
    | ($t.project // "" | if $phys != $root and (. == $phys or startswith($phys + "/")) then $root + .[($phys | length):] else . end) as $p
    | ($c.scope // [])[]
    | sub("[*?\\[].*$"; "") | sub("/+$"; "")
    | [($c.session // ""), (if startswith("/") then . elif . == "" then $p else $p + "/" + . end),
       ($c.holder_label // $c.holder // "?"), ($t.id // "" | .[0:8]), ($t.title // "" | gsub("[\\x1f\\n]"; " ") | .[0:80]), ($c.expires_at // "")]
    | join("\u001f")' <<<"$out" > "$CC_BG_D/claims.tsv.$$" 2>/dev/null && mv -f "$CC_BG_D/claims.tsv.$$" "$CC_BG_D/claims.tsv"
}

# 0 when the claims cache must be refreshed (builtins only).
cc_bg_stale() {
  [[ -e "$CC_BG_D/claims.at" ]] || return 0
  local ttl at=0 now; ttl="$(cc_cfg_raw bash_guard_ttl)"; [[ "$ttl" =~ ^[0-9]+$ ]] || ttl=30
  cc_epoch_now_var now
  [[ -s "$CC_BG_D/claims.at" ]] && IFS= read -r at < "$CC_BG_D/claims.at"
  [[ "$at" =~ ^[0-9]+$ ]] || at=0
  (( now - at >= ttl )) && return 0
  [[ -e "$CC_BG_D/claims.stamp" ]] || return 1   # never filled; failed < 5 s ago
  local db; db="$(cc_bg_seadb)"
  [[ -e "$db" && "$db" -nt "$CC_BG_D/claims.stamp" ]] && return 0
  [[ -e "$db-wal" && "$db-wal" -nt "$CC_BG_D/claims.stamp" ]] && return 0
  return 1
}

# cc_bg_late <PostToolUse payload, any tool> — 0.5.1 (H2-19): after a Bash
# call that started background work, report claimed paths of OTHER
# sessions that changed since the last look (the job's writes land after
# PostToolUse of the call that started it). For a Bash call, only up to its
# own start (cc_bg_check reports the call itself). Sets CC_BG_LATE.
CC_BG_LATE=""
cc_bg_late() {
  local payload="$1" sid="" upper="" tid
  CC_BG_LATE=""
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_bg_session "$sid"
  [[ -e "$CC_BG_B.bgwatch" ]] || return 0
  if [[ -n "$(find "$CC_BG_B.bgwatch" -mmin +10 -print 2>/dev/null)" ]]; then rm -f "$CC_BG_B.bgwatch" 2>/dev/null; return 0; fi
  [[ -s "$CC_BG_D/claims.tsv" ]] || return 0
  if [[ "$payload" =~ \"tool_name\":[[:space:]]*\"Bash\" ]]; then
    tid="$(cc_bg_tid "$payload")"; [[ -n "$tid" && -e "$CC_BG_B.pre.$tid" ]] && upper="$CC_BG_B.pre.$tid"
  fi
  local me ov iso ses path holder ticket title exp; me="$sid"; ov="$(cc_cfg_raw sea_session)"; [[ -n "$ov" ]] && me="$ov"
  cc_now_var iso
  local -a cl=() paths=()
  while IFS=$'\x1f' read -r ses path holder ticket title exp; do
    [[ -n "$path" && "$ses" != "$me" ]] || continue
    [[ -z "$exp" || "$exp" > "$iso" ]] || continue
    cl+=("${path}"$'\x1f'"${holder}"$'\x1f'"${ticket}"$'\x1f'"${title}"$'\x1f'"${exp}")
    [[ -e "$path" ]] && paths+=("$path")
  done < "$CC_BG_D/claims.tsv"
  (( ${#paths[@]} > 0 )) || return 0
  local hits
  if [[ -n "$upper" ]]; then
    hits="$(cc_with_timeout 5 find "${paths[@]}" \( -name .git -o -name node_modules \) -prune -o -type f \( -newer "$CC_BG_B.bgwatch" -o -cnewer "$CC_BG_B.bgwatch" \) ! -newer "$upper" -print 2>/dev/null)"
    touch -r "$upper" "$CC_BG_B.bgwatch" 2>/dev/null || true
  else
    hits="$(cc_with_timeout 5 find "${paths[@]}" \( -name .git -o -name node_modules \) -prune -o -type f \( -newer "$CC_BG_B.bgwatch" -o -cnewer "$CC_BG_B.bgwatch" \) -print 2>/dev/null)"
    : > "$CC_BG_B.bgwatch" 2>/dev/null || true
  fi
  [[ -n "$hits" ]] || return 0
  local out="" n=0 h c cpath
  while IFS= read -r h; do
    [[ -n "$h" ]] || continue
    cpath=""
    for c in "${cl[@]}"; do
      IFS=$'\x1f' read -r path holder ticket title exp <<<"$c"
      if [[ "$h" == "$path" || "$h" == "$path/"* ]]; then cpath="$path"; break; fi
    done
    [[ -n "$cpath" ]] || continue
    n=$((n + 1)); (( n <= 10 )) || continue
    out="${out}
- ${h#"$CC_ROOT"/} — held by ${holder}, ticket ${ticket} \"${title}\" (locks ${cpath#"$CC_ROOT"/}; expires ${exp:-?})"
  done <<<"$hits"
  (( n > 0 )) || return 0
  (( n > 10 )) && out="${out}
- … and $((n - 10)) more"
  CC_BG_LATE="cc-anchor bash guard: since an earlier Bash call of yours started background work, ${n} path(s) inside live sea-lite claims held by OTHER sessions changed after that call returned (by your background job, or by the holder):${out}
If your background job wrote there, stop it and undo the change unless you agreed it with the holder."
  cc_log "bash_guard: ${n} late change(s) inside other sessions' claims after background work"
}

# PostToolUse(Bash): sets CC_BG_CONTEXT (empty: say nothing).
cc_bg_check() {
  local payload="$1" sid="" tid pre
  CC_BG_CONTEXT=""
  [[ "$payload" =~ \"tool_name\":[[:space:]]*\"Bash\" ]] || return 0
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_bg_session "$sid"
  if [[ -e "$CC_BG_B.nobin" ]]; then
    rm -f "$CC_BG_B.nobin" 2>/dev/null
    cc_sea_advise "$sid" "the sea-lite CLI was not found" && CC_BG_CONTEXT="$CC_SEA_ADVICE"
  fi
  [[ -e "$CC_BG_B.off" ]] && return 0
  cc_bg_enabled || return 0
  tid="$(cc_bg_tid "$payload")"
  [[ -n "$tid" ]] || return 0
  pre="$CC_BG_B.pre.$tid"
  [[ -e "$pre" ]] || return 0
  # 0.5.1 (H2-19): this call started background work (`… &`, nohup,
  # setsid, disown): watch the claims for writes that land AFTER it returned
  # (cc_bg_late, on the following tool calls, for up to 10 minutes). The
  # watch starts at this call's own start: a slow PostToolUse must not
  # hide a write that lands while it runs.
  if [[ -e "$CC_BG_B.bgjob.$tid" ]] || cc_bg_starts_job "$payload"; then
    touch -r "$pre" "$CC_BG_B.bgwatch" 2>/dev/null || : > "$CC_BG_B.bgwatch" 2>/dev/null || true
  fi
  rm -f "$CC_BG_B.bgjob.$tid" 2>/dev/null
  if cc_bg_stale; then cc_bg_refresh || true; fi
  local advice=""
  if [[ -s "$CC_BG_D/claims.degraded" ]]; then
    local drc="" good="" nowd what="has no claims to check against"; IFS= read -r drc < "$CC_BG_D/claims.degraded"
    [[ -s "$CC_BG_D/claims.good" ]] && IFS= read -r good < "$CC_BG_D/claims.good"
    cc_epoch_now_var nowd; [[ "$good" =~ ^[0-9]+$ ]] && what="is using the claims it saw $((nowd - good)) s ago"
    cc_sea_advise "$sid" "sea-lite board $([[ "$drc" == 124 ]] && echo "timed out" || echo "failed (exit $drc)"); the Bash guard ${what}" && advice="$CC_SEA_ADVICE"
  elif [[ -e "$CC_BG_D/claims.good" ]]; then
    cc_sea_recovered "$sid"
  fi
  [[ -s "$CC_BG_D/claims.tsv" ]] || { CC_BG_CONTEXT="${CC_BG_CONTEXT:-$advice}"; rm -f "$pre" 2>/dev/null; return 0; }
  local me ov; me="$sid"; ov="$(cc_cfg_raw sea_session)"; [[ -n "$ov" ]] && me="$ov"
  # 0.5.1 (H2-24b): a claim of THIS session is someone else's work too when
  # a different agent of the session took it — a subagent editing the main
  # agent's claim or a sibling's. Known from claims.json (claims taken
  # through the sea_* MCP tools, tagged with the agent_id); a claim of this
  # session that claims.json does not know is treated as the main agent's.
  local myagent; myagent="$(cc_payload_agent "$payload")"
  local owners=""
  if [[ -s "$CC_CLAIMS" ]] && grep -Fq -- "$me" "$CC_BG_D/claims.tsv" 2>/dev/null; then
    owners="$(jq -r --arg s "$sid" '(.claims // {}) | to_entries[] | select((.value.session // "") == $s) | "\(.key[0:8])\u001f\(.value.agent // "")"' "$CC_CLAIMS" 2>/dev/null)"
  fi
  local iso; cc_now_var iso
  local ses path holder ticket title exp prevp="" owner
  if [[ -s "$CC_BG_B.present.$tid" ]]; then prevp="$(cat "$CC_BG_B.present.$tid" 2>/dev/null)"
  elif [[ -s "$CC_BG_B.present" ]]; then prevp="$(cat "$CC_BG_B.present" 2>/dev/null)"; fi
  rm -f "$CC_BG_B.present.$tid" 2>/dev/null
  local -a cl=() paths=() gone=() present=()
  while IFS=$'\x1f' read -r ses path holder ticket title exp; do
    [[ -n "$path" ]] || continue
    if [[ "$ses" == "$me" ]]; then
      owner=""
      if [[ -n "$owners" ]]; then
        local ot oa
        while IFS=$'\x1f' read -r ot oa; do [[ "$ot" == "$ticket" ]] && { owner="$oa"; break; }; done <<<"$owners"
      fi
      [[ "$owner" == "$myagent" ]] && continue
      holder="${holder} — your own session's $([[ -n "$owner" ]] && printf 'subagent %s' "$owner" || printf 'main agent')"
    fi
    [[ -z "$exp" || "$exp" > "$iso" ]] || continue
    cl+=("${path}"$'\x1f'"${holder}"$'\x1f'"${ticket}"$'\x1f'"${title}"$'\x1f'"${exp}")
    if [[ -e "$path" || -L "$path" ]]; then paths+=("$path"); present+=("$path")
    elif [[ -d "${path%/*}" ]] && ! [[ "${path%/*}" -ot "$pre" ]]; then gone+=("$path (removed)")
    else
      # 0.5.1 (H2-18): gone through an ancestor (rm -rf src, mv src x, a
      # checkout without src/): the nearest directory that still exists
      # changed during this call, and the path existed before it (seen at
      # PreToolUse or at the last check; else git knew it: in the index, or
      # in the commit HEAD was on before a checkout).
      local anc="${path%/*}" was=0 relp="${path#"$CC_ROOT"/}"
      while [[ -n "$anc" && ! -d "$anc" ]]; do anc="${anc%/*}"; done
      if [[ -n "$anc" ]] && ! [[ "$anc" -ot "$pre" ]]; then
        if [[ -n "$prevp" ]]; then grep -Fxq -- "$path" <<<"$prevp" && was=1
        elif [[ "$relp" != "$path" ]] && command -v git >/dev/null 2>&1; then
          if [[ -n "$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 3 git ls-files -- "$relp" 2>/dev/null | head -1)" ]]; then was=1
          elif (cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 3 git cat-file -e "HEAD@{1}:$relp" 2>/dev/null); then was=1; fi
        fi
      fi
      (( was )) && gone+=("$path (removed)")
    fi
  done < "$CC_BG_D/claims.tsv"
  if (( ${#present[@]} > 0 )); then printf '%s\n' "${present[@]}" > "$CC_BG_B.present" 2>/dev/null || true
  else rm -f "$CC_BG_B.present" 2>/dev/null; fi
  (( ${#cl[@]} > 0 )) || { CC_BG_CONTEXT="${CC_BG_CONTEXT:-$advice}"; rm -f "$pre" 2>/dev/null; return 0; }
  # One find over the claimed paths: modified OR status-changed after the stamp.
  local hits="" rc=0 note=""
  if (( ${#paths[@]} > 0 )); then
    hits="$(cc_with_timeout 5 find "${paths[@]}" \( -name .git -o -name node_modules \) -prune -o \( -newer "$pre" -o -cnewer "$pre" \) -print 2>/dev/null)"; rc=$?
    if (( rc == 124 )); then
      # Too big to scan in time: what git says changed under those paths
      # (cannot tell this call's changes from earlier ones; say so).
      note=" (find timed out; per git status — may include earlier changes)"
      local -a rel=() p
      for p in "${paths[@]}"; do rel+=("${p#"$CC_ROOT"/}"); done
      hits="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 5 git status --porcelain -- "${rel[@]}" 2>/dev/null | while IFS= read -r p; do p="${p:3}"; p="${p#*-> }"; printf '%s\n' "$CC_ROOT/$p"; done)"
      cc_log_once bg_find_timeout "bash_guard: find over claimed paths timed out; fell back to git status"
    fi
  fi
  rm -f "$pre" 2>/dev/null
  local -a found=() h
  if [[ -n "$hits" ]]; then
    local -a all=()
    while IFS= read -r h; do [[ -n "$h" ]] && all+=("${h%/}"); done <<<"$hits"
    # A directory whose entries changed is reported only when nothing inside
    # it was (an entry was removed or renamed away).
    for h in "${all[@]}"; do
      if [[ -d "$h" && ! -L "$h" ]]; then
        local inner=0 o
        for o in "${all[@]}"; do [[ "$o" == "$h/"* ]] && { inner=1; break; }; done
        (( inner )) && continue
        found+=("$h/ (entries added, removed or renamed)")
      else found+=("$h"); fi
    done
  fi
  found+=(${gone[@]+"${gone[@]}"})
  (( ${#found[@]} > 0 )) || { CC_BG_CONTEXT="${CC_BG_CONTEXT:-$advice}"; return 0; }
  # Drop git-ignored files (build output) with one bounded `git status`.
  local ignored=""
  if command -v git >/dev/null 2>&1; then
    local -a gp=() l
    for l in "${found[@]}"; do l="${l% (entries added, removed or renamed)}"; l="${l% (removed)}"; gp+=("${l%/}"); done
    ignored="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 3 git status --porcelain --ignored=matching -- "${gp[@]}" 2>/dev/null | while IFS= read -r l; do [[ "$l" == '!! '* ]] && printf '%s\n' "${l#!! }"; done)"
  fi
  local out="" n=0 shown=0 rel l2 c cpath bare
  for h in "${found[@]}"; do
    bare="${h% (entries added, removed or renamed)}"; bare="${bare% (removed)}"; bare="${bare%/}"
    rel="${h#"$CC_ROOT"/}"
    # Which claim covers it (first match).
    holder="?"; ticket="?"; title=""; exp=""; cpath=""
    for c in "${cl[@]}"; do
      IFS=$'\x1f' read -r path holder ticket title exp <<<"$c"
      if [[ "$bare" == "$path" || "$bare" == "$path/"* ]]; then cpath="$path"; break; fi
    done
    [[ -n "$cpath" ]] || continue
    # Git-ignored output (build artefacts) inside a claim is dropped — unless
    # the claim itself is on an ignored path (0.5.1, H2-24a: config/, .env …).
    if [[ -n "$ignored" ]]; then
      local skip=0 ig crel="${cpath#"$CC_ROOT"/}"
      while IFS= read -r ig; do
        [[ -n "$ig" ]] || continue
        ig="${ig%/}"
        [[ "$crel" == "$ig" || "$crel" == "$ig"/* ]] && continue   # ignore covers the whole claim
        [[ "${bare#"$CC_ROOT"/}" == "$ig" || "${bare#"$CC_ROOT"/}" == "$ig"/* ]] && { skip=1; break; }
      done <<<"$ignored"
      (( skip )) && continue
    fi
    n=$((n + 1))
    (( shown < 10 )) || continue
    shown=$((shown + 1))
    l2="${cpath#"$CC_ROOT"/}"
    out="${out}
- ${rel} — held by ${holder}, ticket ${ticket} \"${title}\" (locks ${l2}; expires ${exp:-?})"
  done
  (( n > 0 )) || { CC_BG_CONTEXT="${CC_BG_CONTEXT:-$advice}"; return 0; }
  (( n > shown )) && out="${out}
- … and $((n - shown)) more"
  [[ -n "$advice" ]] && note="${note} (sea-lite board is not answering: checked against the claims last seen)"
  CC_BG_CONTEXT="cc-anchor bash guard: that Bash call changed ${n} path(s) inside live sea-lite claims held by OTHER sessions${note}:${out}
Those paths are another agent's work in progress. Undo your change (git checkout -- <path>, or delete the new file) unless you agreed it with the holder; the Edit/Write scope guard does not see Bash edits."
  cc_log "bash_guard: ${n} path(s) inside other sessions' claims after Bash"
  return 0
}
