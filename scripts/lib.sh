# cc_find_cli NAME — echo the path of the kronicle-lite / sea-lite CLI (an
# executable on PATH or a dist/cli.js to run with node), or nothing.
# Order: CC_ANCHOR_<NAME>_BIN, PATH, the Claude Code plugin cache (the
# isokron plugins pin the package under node_modules), <root>/node_modules,
# the npx cache (~/.npm/_npx/*/node_modules).
cc_find_cli() {
  local name="$1" envname v f
  envname="CC_ANCHOR_$(printf '%s' "$name" | tr '[:lower:]-' '[:upper:]_')_BIN"
  v="${!envname:-}"
  if [[ -n "$v" ]]; then printf '%s' "$v"; return 0; fi
  if v="$(command -v "$name" 2>/dev/null)"; then printf '%s' "$v"; return 0; fi
  # Last: the npx cache. The isokron-plugins marketplace launches the MCP
  # servers with `npx -y <name>@<pin> serve`, so a plugin-only install has
  # the CLI there and nowhere else.
  for f in "${HOME}"/.claude/plugins/cache/*/"$name"/*/node_modules/"$name"/dist/cli.js \
           "${HOME}"/.claude/plugins/cache/*/*/*/node_modules/"$name"/dist/cli.js \
           "${CC_ROOT}"/node_modules/"$name"/dist/cli.js \
           "${npm_config_cache:-${HOME}/.npm}"/_npx/*/node_modules/"$name"/dist/cli.js; do
    [[ -f "$f" ]] && { printf '%s' "$f"; return 0; }
  done
  return 1
}

# cc_with_timeout SECS CMD… — run CMD, killing it (and its children) after
# SECS; exit status 124 on timeout, like GNU timeout. Uses timeout(1) or
# gtimeout(1) when present. macOS ships neither, and the old code simply ran
# without a bound there, so a hung sea-lite stalled every Edit until Claude
# Code's own hook timeout. The fallback runs CMD in its own process group
# (set -m) with a watchdog that signals the whole group, so a wrapper
# script's children cannot keep a $(…) capture open after the kill.
# CC_ANCHOR_TEST_NO_TIMEOUT_BIN=1 forces the fallback (tests).
cc_with_timeout() {
  local to="$1"; shift
  if [[ "${CC_ANCHOR_TEST_NO_TIMEOUT_BIN:-0}" != 1 ]]; then
    if command -v timeout >/dev/null 2>&1; then timeout "$to" "$@"; return; fi
    if command -v gtimeout >/dev/null 2>&1; then gtimeout "$to" "$@"; return; fi
  fi
  (
    set -m
    "$@" </dev/null &
    cmd=$!
    ( trap 'kill "${s:-}" 2>/dev/null; exit 0' TERM
      sleep "$to" & s=$!; wait "$s"; kill -TERM -- "-$cmd" 2>/dev/null ) </dev/null >/dev/null 2>&1 &
    dog=$!
    wait "$cmd"; rc=$?
    kill -TERM -- "-$dog" 2>/dev/null
    (( rc == 143 )) && rc=124
    exit "$rc"
  )
}

# cc_run_cli NAME ARGS… — run the CLI found by cc_find_cli (node for *.js).
# Returns 127 when none is found.
cc_run_cli() {
  local name="$1" p; shift
  p="$(cc_find_cli "$name")" || return 127
  if [[ "$p" == *.js || "$p" == *.mjs ]]; then node "$p" "$@"; else "$p" "$@"; fi
}

# cc_log MSG — append "<iso> MSG" to the runtime log (never stdout).
cc_log() { cc_ensure_dirs || return 0; local n; cc_now_var n; printf '%s %s\n' "$n" "$*" >> "$CC_LOG" 2>/dev/null || true; }

# cc_log_once KEY MSG — log at most once per hour per key (latch file mtime).
cc_log_once() {
  local key="$1"; shift
  local d="$CC_RUN/once" f
  f="$d/$key"
  mkdir -p "$d" 2>/dev/null || return 0
  if [[ -e "$f" ]] && [[ -n "$(find "$f" -mmin -60 2>/dev/null)" ]]; then return 0; fi
  : > "$f" 2>/dev/null || true
  cc_log "$@"
}

# ── claims (sea-lite) ──────────────────────────────────────────────────
# cc_claims_update <PostToolUse payload> — when the tool is a sea-lite
# claim/next/create/release/transition/refresh call, fold its result into
# claims.json via claims.jq. Also invalidates the scope cache (claims moved).
cc_claims_update() {
  local payload="$1" name
  [[ "$payload" =~ \"tool_name\":[[:space:]]*\"([^\"]*)\" ]] || return 0
  name="${BASH_REMATCH[1]}"
  [[ "$name" =~ $CC_SEA_TOOL_RE ]] || return 0
  cc_have_jq || return 0
  cc_ensure_dirs || return 0
  local now out cur=/dev/null
  cc_now_var now
  [[ -s "$CC_CLAIMS" ]] && cur="$CC_CLAIMS"
  out="$(jq -c -f "$CC_LIB_DIR/claims.jq" --slurpfile claims "$cur" --arg now "$now" --arg terminal_re "$CC_TERMINAL_RE" <<<"$payload" 2>/dev/null)" || return 0
  [[ -n "$out" ]] || return 0
  printf '%s\n' "$out" > "$CC_CLAIMS.tmp.$$" && mv -f "$CC_CLAIMS.tmp.$$" "$CC_CLAIMS"
  rm -f "$CC_SCOPE_CACHE" 2>/dev/null || true
}

# cc_claims_live [agent_id|*] [session_id|*] — compact JSON array of live
# claims [{ticket_id, claim_token, expires, agent, session, taken}], newest
# first. agent "*" (default) = every agent; "" = main agent only. session
# "*" (default) = every session. claims.json lives in the project's run dir,
# which every Claude Code session of the project shares, so a guard acting
# for one session must pass its session_id: another session's claims (and
# their tokens) are not its business.
cc_claims_live() {
  local who="${1-*}" ses="${2-*}"
  [[ -s "$CC_CLAIMS" ]] || { echo '[]'; return 0; }
  cc_have_jq || { echo '[]'; return 0; }
  local now; cc_now_var now
  jq -c --arg now "$now" --arg who "$who" --arg ses "$ses" '
    (.claims // {}) | to_entries
    | map(.value + {ticket_id: .key})
    | map(select(.expires > $now))
    | map(select($who == "*" or (.agent // "") == $who))
    | map(select($ses == "*" or $ses == "" or (.session // "") == $ses))
    | sort_by(.taken) | reverse' "$CC_CLAIMS" 2>/dev/null || echo '[]'
}

# cc_sea_heartbeat <PostToolUse payload> — keep this session's sea-lite
# leases alive while it works (sea-lite >= 0.4.0). At most once per config
# `heartbeat_interval` s (default 60) per session, run
# `sea-lite heartbeat --session <session_id>` in the background; it renews
# every live claim of the session by its own lease and never revives a
# lapsed one. Switch `heartbeat`: on / off; unset = on when this project has
# seen claims (claims.json) or sea-lite is configured. Hot path when not
# due: bash builtins only (one read of the stamp file).
cc_sea_heartbeat() {
  local payload="$1" sid="" now="" last="" stamp iv sw short
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  [[ -n "$sid" ]] || return 0
  short="${sid//[^A-Za-z0-9]/}"; short="${short:0:8}"
  stamp="$CC_RUN/hb-${short:-nosession}"
  printf -v now '%(%s)T' -1 2>/dev/null || now="$(date +%s)"
  [[ "$now" =~ ^[0-9]+$ ]] || now="$(date +%s)"
  iv="${CC_ANCHOR_HEARTBEAT_INTERVAL:-}"
  [[ "$iv" =~ ^[0-9]+$ ]] || { iv="$(cc_cfg_raw heartbeat_interval)"; [[ "$iv" =~ ^[0-9]+$ ]] || iv=60; }
  if [[ -s "$stamp" ]]; then IFS= read -r last < "$stamp" || true; fi
  if [[ "$last" =~ ^[0-9]+$ ]] && (( now - last < iv )); then return 0; fi
  # Stamp first: the switch / detection below then costs at most once per interval too.
  cc_ensure_dirs || return 0
  printf '%s\n' "$now" > "$stamp" 2>/dev/null || return 0
  sw="$(cc_cfg_raw heartbeat)"
  case "$sw" in
    0|false|no|off) return 0;;
    1|true|yes|on) ;;
    *) [[ -s "$CC_CLAIMS" ]] || cc_sea_configured || return 0;;
  esac
  local bin ov actor
  bin="$(cc_find_cli sea-lite)" || { cc_log_once hb_nobin "heartbeat: sea-lite CLI not found; leases renew only on sea-lite tool calls"; return 0; }
  ov="$(cc_cfg_raw sea_session)"; [[ -n "$ov" ]] && sid="$ov"
  actor="$(cc_cfg_raw sea_actor)"
  local args=(heartbeat --session "$sid")
  [[ -n "$actor" ]] && args+=(--actor "$actor")
  [[ -n "${CC_ANCHOR_SEA_DATA_DIR:-}" ]] && args+=(--data-dir "$CC_ANCHOR_SEA_DATA_DIR")
  local run=("$bin"); [[ "$bin" == *.js || "$bin" == *.mjs ]] && run=(node "$bin")
  if [[ "${CC_ANCHOR_SYNC:-0}" == "1" ]]; then
    "${run[@]}" "${args[@]}" >> "$CC_LOG" 2>&1 || true
  else
    ( "${run[@]}" "${args[@]}" >> "$CC_LOG" 2>&1 & ) >/dev/null 2>&1
  fi
  return 0
}

# cc_pending_add <claims-json-array> <reason> — append to pending-release.jsonl (dedup by ticket).
cc_pending_add() {
  local arr="$1" reason="$2" line
  cc_have_jq || return 0
  cc_ensure_dirs || return 0
  [[ "$arr" == "[]" ]] && return 0
  local existing=""; [[ -s "$CC_PENDING" ]] && existing="$(cat "$CC_PENDING")"
  local now; cc_now_var now
  jq -r --arg now "$now" --arg reason "$reason" --arg existing "$existing" '
    ($existing | split("\n") | map(select(. != "") | try fromjson catch empty) | map(.ticket_id)) as $have
    | .[] | select(.ticket_id as $t | ($have | index($t)) == null)
    | {ts: $now, ticket_id, claim_token, agent, session, reason: $reason} | tojson' <<<"$arr" 2>/dev/null \
    | while IFS= read -r line; do [[ -n "$line" ]] && printf '%s\n' "$line" >> "$CC_PENDING"; done
  return 0
}

# cc_pending_live — pending releases whose claim is still live (others are
# pruned from the file). Echoes a JSON array.
cc_pending_live() {
  [[ -s "$CC_PENDING" ]] || { echo '[]'; return 0; }
  cc_have_jq || { echo '[]'; return 0; }
  local live out
  live="$(cc_claims_live '*')"
  out="$(jq -cs --argjson live "$live" '
    ($live | map(.ticket_id)) as $ids
    | map(select(.ticket_id as $t | ($ids | index($t)) != null))' "$CC_PENDING" 2>/dev/null)" || { echo '[]'; return 0; }
  if [[ "$out" == "[]" ]]; then rm -f "$CC_PENDING" 2>/dev/null; else jq -c '.[]' <<<"$out" > "$CC_PENDING.tmp.$$" 2>/dev/null && mv -f "$CC_PENDING.tmp.$$" "$CC_PENDING"; fi
