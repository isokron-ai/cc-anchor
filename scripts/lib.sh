# ═══════════════════ 0.4.0: kronicle-lite retraction push + pulse ═══════════════════
#
# Track B (agent-memory-bench, T1): agents that orient at session start never
# re-orient before a deploy (0/36 pull runs); pushing new retractions into the
# context after each tool call fixed it (10/10). Two hooks share this code:
#
#   PostToolUse (push)   after every tool call, fetch the retractions that
#                        landed since this session's cursor and inject them
#                        as additionalContext; advance + persist the cursor.
#   PreToolUse (pulse)   before a world-changing Bash command (config
#                        `pulse_match`), same fetch; an unreconciled semantic
#                        safety/behavioral retraction denies the command
#                        (config `pulse_mode`: deny | warn).
#
# Per-session runtime files under $CC_RUN/push/<sid8>.*:
#   cfg      "<data dir>\n<cli path>" — resolved once per session
#   off      kronicle-lite not configured / no CLI: the hooks are inert
#   cursor   full kronicle-lite cursor (actor cc-anchor-<sid8>)
#   seq      chain head seq the cursor was issued at
#   stamp    mtime gate: touched just BEFORE each read of the chain. While
#            kronicle-lite.db and its -wal are older than the stamp nothing
#            can have changed, so the hot path costs two builtin `-ot` tests
#            and no process. A change makes the next call run a read-only
#            `orient --focus pulse` (head seq) and, only if the head moved,
#            `orient --cursor C --focus retractions`.
#   pending  blocking retractions the push delivered on the LAST tool result.
#            Any later tool call clears it (the agent had a turn to act on
#            it); a world-changing command issued straight after the push is
#            denied first.
#   fail     epoch of the last CLI failure (back-off: retry after 60 s)
#   integrity  "<seq>\x1f<problem>" while kronicle-lite reports integrity.ok
#            false (corrupt / tampered store); intwarned: the problem this
#            agent was last warned about (once per distinct problem)
#   down     consecutive push/pulse calls that could not read the store (CLI
#            missing from the cache, timeout, error, non-JSON); downwarned:
#            the one "feed offline" advisory of this outage was given
#
# Fail-open everywhere: a missing CLI, a slow or broken store, a timeout
# (config `push_timeout` s, default 3, per CLI call) never blocks a tool call
# and never prints anything but valid hook JSON; one log line says why.

CC_KL_B=""; CC_KL_S=""; CC_KL_SID=""; CC_KL_AGENT=""; CC_KL_DD=""; CC_KL_BIN=""; CC_KL_ACTOR=""; CC_KL_FAILED=0
KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0; KL_SEQ=""

cc_epoch_now_var() {  # NAME — epoch seconds without a fork on bash >= 4.2
  local __t
  # Tests drive the clock explicitly (second-boundary logic) instead of
  # depending on wall-clock luck.
  if [[ "${CC_ANCHOR_TEST_NOW:-}" =~ ^[0-9]+$ ]]; then printf -v "$1" '%s' "$CC_ANCHOR_TEST_NOW"; return 0; fi
  printf -v __t '%(%s)T' -1 2>/dev/null || __t=""
  [[ "$__t" =~ ^[0-9]+$ ]] || __t="$(date +%s)"
  printf -v "$1" '%s' "$__t"
}

# cc_kl_session <session_id> [agent_id] — file prefixes (builtins only).
#   CC_KL_S  per session: cfg / off / fail (the CLI and its health are shared)
#   CC_KL_B  per AGENT:   cursor / seq / stamp / pending. The main agent is
#            "<sid8>", a subagent "<sid8>.a-<agent_id>" (or "a-h<hash of the
#            whole id>" when it is long or not filename-safe). Each subagent has its
#            own cursor, seeded from the main agent's at SubagentStart, so a
#            retraction one agent consumed still reaches its siblings and the
#            parent (each exactly once).
cc_kl_session() {
  local s="${1:-nosession}" a="${2:-}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  CC_KL_SID="${s:-nosession}"
  CC_KL_S="$CC_RUN/push/$CC_KL_SID"
  # agent_id is an opaque string (docs: "agent-abc123", "def456"). Keep it
  # whole when it is filename-safe and short — distinct ids then get distinct
  # files with no process; otherwise a hash of the WHOLE id (never a prefix
  # of it: two subagents must not share a cursor).
  if [[ -z "$a" ]]; then CC_KL_AGENT=""
  elif (( ${#a} <= 64 )) && [[ "$a" =~ ^[A-Za-z0-9_-]+$ ]]; then CC_KL_AGENT="$a"
  else CC_KL_AGENT="h$(cc_hash "$a")"; fi
  if [[ -n "$CC_KL_AGENT" ]]; then CC_KL_B="$CC_KL_S.a-$CC_KL_AGENT"; else CC_KL_B="$CC_KL_S"; fi
}

# cc_payload_agent <payload> — the hook's agent_id ("" in the main agent).
# jq only when the payload mentions agent_id at all (subagents), and read
# from the top level: a tool_input may carry its own "agent_id".
cc_payload_agent() {
  [[ "$1" == *'"agent_id"'* ]] || return 0
  jq -r '.agent_id // "" | tostring' <<<"$1" 2>/dev/null || true
}

# cc_kl_seed — start a subagent's cursor where its parent's is (copy), so
# everything the parent has not consumed yet reaches the subagent too.
# Falls back to the head when the parent has no cursor. Main agent: init.
cc_kl_seed() {
  if [[ -n "$CC_KL_AGENT" && -s "$CC_KL_S.cursor" ]]; then
    cp -f "$CC_KL_S.cursor" "$CC_KL_B.cursor.$$" 2>/dev/null && mv -f "$CC_KL_B.cursor.$$" "$CC_KL_B.cursor" || return 1
    if [[ -s "$CC_KL_S.seq" ]]; then cp -f "$CC_KL_S.seq" "$CC_KL_B.seq" 2>/dev/null || true; fi
    rm -f "$CC_KL_B.stamp" 2>/dev/null
    return 0
  fi
  cc_kl_init
}

# cc_kl_forget — drop a stopped subagent's cursor files.
cc_kl_forget() {
  [[ -n "$CC_KL_AGENT" ]] || return 0
  rm -f "$CC_KL_B.cursor" "$CC_KL_B.seq" "$CC_KL_B.stamp" "$CC_KL_B.pending" "$CC_KL_B.parked" "$CC_KL_B.intwarned" "$CC_KL_B.oneliner" \
        "$CC_KL_B.actor" "$CC_KL_B.klpend" "$CC_KL_B.pendcalls" "$CC_KL_B.reminded" "$CC_KL_B.wcattempt" 2>/dev/null || true
}

# Data dir of the kronicle-lite store the agent's MCP server uses.
# CC_ANCHOR_KRONICLE_DATA_DIR > config kronicle_data_dir > the kronicle MCP
# server's --data-dir / KRONICLE_LITE_DATA_DIR in .mcp.json or ~/.claude.json
# > $KRONICLE_LITE_DATA_DIR > "" (the CLI's own default, ~/.kronicle-lite).
cc_kl_data_dir() {
  local v f
  v="${CC_ANCHOR_KRONICLE_DATA_DIR:-}"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  v="$(cc_cfg_raw kronicle_data_dir)"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  for f in "$CC_ROOT/.mcp.json" "${HOME}/.claude.json"; do
    [[ -s "$f" ]] || continue
    v="$(jq -r --arg root "$CC_ROOT" '
        ((.mcpServers // {}) + ((.projects // {})[$root].mcpServers // {})) | to_entries
        | map(select((.key | ascii_downcase | test("kronicle")) or ((.value.args // []) | tostring | test("kronicle"))) | .value)
        | map(((.args // []) | index("--data-dir") as $i | if $i == null then null else .[$i + 1] end) // .env.KRONICLE_LITE_DATA_DIR // empty)
        | first // empty' "$f" 2>/dev/null)"
    [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  done
  printf '%s' "${KRONICLE_LITE_DATA_DIR:-}"
}

# The actor whose reads count for kronicle-lite's `pending` (0.8.0): the
# agent's MCP server actor. CC_ANCHOR_KRONICLE_ACTOR > config kronicle_actor
# > the kronicle server's --actor / KRONICLE_LITE_ACTOR in .mcp.json or
# ~/.claude.json > $KRONICLE_LITE_ACTOR > "local-agent" (the server default).
cc_kl_actor_detect() {
  local v f
  v="${CC_ANCHOR_KRONICLE_ACTOR:-}"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  v="$(cc_cfg_raw kronicle_actor)"; [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  for f in "$CC_ROOT/.mcp.json" "${HOME}/.claude.json"; do
    [[ -s "$f" ]] || continue
    v="$(jq -r --arg root "$CC_ROOT" '
        ((.mcpServers // {}) + ((.projects // {})[$root].mcpServers // {})) | to_entries
        | map(select((.key | ascii_downcase | test("kronicle")) or ((.value.args // []) | tostring | test("kronicle"))) | .value)
        | map(((.args // []) | index("--actor") as $i | if $i == null then null else .[$i + 1] end) // .env.KRONICLE_LITE_ACTOR // empty)
        | first // empty' "$f" 2>/dev/null)"
    [[ -n "$v" ]] && { printf '%s' "$v"; return 0; }
  done
  printf '%s' "${KRONICLE_LITE_ACTOR:-local-agent}"
}

# The effective actor for THIS agent: one it named itself in a kronicle-lite
# tool call (actor_id, learned by the PostToolUse hook) wins over the
# session's server actor. Builtins only.
cc_kl_agent_actor() {
  local a=""
  [[ -s "$CC_KL_B.actor" ]] && IFS= read -r a < "$CC_KL_B.actor"
  printf '%s' "${a:-$CC_KL_ACTOR}"
}

# cc_kl_enabled — 0 when the push/pulse should run for this session (and
# CC_KL_DD / CC_KL_BIN are set). Switch `push`: on | off | auto (default:
# on when kronicle-lite is configured for the project). Resolved once per
# session into <sid8>.cfg / <sid8>.off; env CC_ANCHOR_PUSH=0 always wins.
cc_kl_enabled() {
  [[ "${CC_ANCHOR_KRONICLE:-}" == 0 ]] && return 1
  local sw; sw="$(cc_cfg_raw push)"
  case "$sw" in 0|false|no|off) return 1;; esac
  if [[ -s "$CC_KL_S.cfg" ]]; then
    { IFS= read -r CC_KL_DD; IFS= read -r CC_KL_BIN; IFS= read -r CC_KL_ACTOR; } < "$CC_KL_S.cfg"
    [[ -n "$CC_KL_ACTOR" ]] || CC_KL_ACTOR="$(cc_kl_actor_detect)"
    [[ -n "$CC_KL_BIN" ]] && return 0
  fi
  [[ -e "$CC_KL_S.off" ]] && return 1
  mkdir -p "$CC_RUN/push" 2>/dev/null || return 1
  case "$sw" in
    1|true|yes|on) ;;
    *) cc_kronicle_configured || { : > "$CC_KL_S.off"; return 1; };;
  esac
  CC_KL_BIN="$(cc_find_cli kronicle-lite)" || {
    : > "$CC_KL_S.off"
    cc_log_once kl_nobin "push: kronicle-lite is configured but its CLI was not found (PATH, plugin cache, CC_ANCHOR_KRONICLE_LITE_BIN); retraction push/pulse off"
    return 1; }
  CC_KL_DD="$(cc_kl_data_dir)"
  CC_KL_ACTOR="$(cc_kl_actor_detect)"
  printf '%s\n%s\n%s\n' "$CC_KL_DD" "$CC_KL_BIN" "$CC_KL_ACTOR" > "$CC_KL_S.cfg" 2>/dev/null || return 1
  return 0
}

# cc_kl_orient ARGS… — `kronicle-lite orient --json` for this session's actor,
# bounded by push_timeout. Prints the JSON; non-zero on failure / timeout.
cc_kl_orient() {
  local to; to="$(cc_cfg_raw push_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=3
  # --pending-actor (kronicle-lite >= 0.8.0; older versions ignore it): the
  # briefing then carries pending[] for the AGENT's reads, not the hook's.
  local -a a=(orient --json --actor "cc-anchor-$CC_KL_SID" --pending-actor "$(cc_kl_agent_actor)" --cwd "$CC_ROOT")
  [[ -n "$CC_KL_DD" ]] && a+=(--data-dir "$CC_KL_DD")
  if [[ "$CC_KL_BIN" == *.js || "$CC_KL_BIN" == *.mjs ]]; then cc_with_timeout "$to" node "$CC_KL_BIN" "${a[@]}" "$@" 2>/dev/null
  else cc_with_timeout "$to" "$CC_KL_BIN" "${a[@]}" "$@" 2>/dev/null; fi
}

# Unavailable bookkeeping: every push/pulse call that could not read the
# store (failure, or inside the back-off) counts; any successful read resets.
cc_kl_down() {
  local n=0; [[ -s "$CC_KL_S.down" ]] && IFS= read -r n < "$CC_KL_S.down"
  [[ "$n" =~ ^[0-9]+$ ]] || n=0
  printf '%s\n' "$((n + 1))" > "$CC_KL_S.down" 2>/dev/null || true
}
cc_kl_up() {
  [[ -e "$CC_KL_S.down" ]] || return 0
  rm -f "$CC_KL_S.down" "$CC_KL_S.downwarned" 2>/dev/null
  cc_log "push: kronicle-lite readable again; retraction feed back online"
}

# cc_kl_integrity_note <seq> <problem> | ok — record what the last briefing
# said about store integrity.
cc_kl_integrity_note() {
  if [[ "$1" == ok ]]; then
    [[ -e "$CC_KL_S.integrity" ]] || return 0
    rm -f "$CC_KL_S.integrity" 2>/dev/null
    cc_log "push: kronicle-lite integrity ok again"
    return 0
  fi
  local cur=""; [[ -s "$CC_KL_S.integrity" ]] && IFS= read -r cur < "$CC_KL_S.integrity"
  [[ "$cur" == "$1"$'\x1f'"$2" ]] && return 0
  printf '%s\x1f%s\n' "$1" "$2" > "$CC_KL_S.integrity" 2>/dev/null || true
  cc_log "push: kronicle-lite INTEGRITY FAILURE at seq $1: $2"
}

# Parse one orient JSON's integrity (any focus): sets the note when ok:false.
# Echoes nothing; returns 0 when the store reported a failure.
cc_kl_integrity_from() {
  local line
  line="$(jq -r 'if (.integrity | type) == "object" and .integrity.ok == false
    then "fail\u001f\(.integrity.seq // .integrity.at_seq // .integrity.first_bad_seq // "?")\u001f\(.integrity.problem // .integrity.error // "integrity check failed" | tostring | gsub("\\s+"; " ") | .[0:240])"
    elif (.integrity | type) == "object" and .integrity.ok == true then "ok" else "" end' <<<"$1" 2>/dev/null)"
  case "$line" in
    fail*) local s p; IFS=$'\x1f' read -r _ s p <<<"$line"; cc_kl_integrity_note "$s" "$p"; return 0;;
    ok) cc_kl_integrity_note ok;;
  esac
  return 1
}

# cc_kl_pending_note <orient JSON> — record what kronicle-lite (>= 0.8.0)
# says is still pending for this agent's actor:
#   <S>.klcap / <S>.klnocap  this kronicle-lite reports `pending` / does not
#   <B>.klpend               "count\x1fhidden\x1factor\x1fslugs" then one
#                            "- …" line per item (at most 6)
# Builtins + one jq. A briefing without pending_count (kronicle-lite <= 0.7.0)
# switches the gate back to the retraction-since-last-look logic.
cc_kl_pending_note() {
  local r
  r="$(jq -r 'def clip($n): if . == null then null else tostring | gsub("\\s+"; " ") | if length > $n then .[0:$n - 1] + "…" else . end end;
    if (.pending_count | type) != "number" then "nocap" else
      "\(.pending_count)\u001f\(.pending_hidden // 0)\u001f\(.pending_actor // "")\u001f\([(.pending // [])[] | .doc_slug // empty] | unique | join(", "))",
      ((.pending // [])[0:6][] |
        "- " + ([(.doc_slug // empty), ((.heading_path // []) | map(tostring) | join(" › ") | select(. != ""))] | join(" › "))
        + " (seq \(.seq // "?"), \(.change // .kind // "?")/\(.severity // "?")): read \"\(.old_text // "?" | clip(120))\" → "
        + (if .current == null then "now REMOVED" else "now \"\(.new_text // "?" | clip(120))\"" end)
        + (if .diff != null then "; diff: \(.diff | clip(200))" else "" end)
        + (if (.derived_notes // []) | length > 0 then "; your notes derived from it: \((.derived_notes | map(if type == "object" then (.doc_slug // .slug // .block_id // "?") else tostring end) | join(", ")) | clip(120))" else "" end)
        + (if .resolve != null then " — \(.resolve | clip(160))" else "" end)),
      (if (.pending_count // 0) > 6 then "- … and \(.pending_count - 6) more (kronicle-lite pending --actor \(.pending_actor // "?"))" else empty end)
    end' <<<"$1" 2>/dev/null)" || return 0
  if [[ "$r" == nocap ]]; then
    [[ -e "$CC_KL_S.klcap" ]] && rm -f "$CC_KL_S.klcap" 2>/dev/null
    [[ -e "$CC_KL_B.klpend" ]] && rm -f "$CC_KL_B.klpend" 2>/dev/null
    [[ -e "$CC_KL_S.klnocap" ]] || : > "$CC_KL_S.klnocap"
    return 0
  fi
  [[ -n "$r" ]] || return 0
  [[ -e "$CC_KL_S.klcap" ]] || { : > "$CC_KL_S.klcap"; rm -f "$CC_KL_S.klnocap" 2>/dev/null; }
  printf '%s\n' "$r" > "$CC_KL_B.klpend.$$" 2>/dev/null && mv -f "$CC_KL_B.klpend.$$" "$CC_KL_B.klpend"
}

# Pending count for this agent from the last briefing ("" = unknown).
cc_kl_pending_count() {
  [[ -s "$CC_KL_B.klpend" ]] || return 0
  local l=""; IFS= read -r l < "$CC_KL_B.klpend"
  l="${l%%$'\x1f'*}"
  [[ "$l" =~ ^[0-9]+$ ]] && printf '%s' "$l"
}

# Force a fresh pending read (the pulse, when it has none for this agent).
cc_kl_pending_refresh() {
  local out rc
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  (( rc == 0 )) && [[ -n "$out" ]] || return 1
  cc_kl_pending_note "$out"
}

cc_kl_fail() {  # rc — remember a failure (60 s back-off), log once per hour
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$CC_KL_S.fail" 2>/dev/null || true
  CC_KL_FAILED=1
  cc_kl_down
  if [[ "$1" == 124 ]]; then cc_log_once kl_timeout "push: kronicle-lite orient timed out (push_timeout); failing open"
  else cc_log_once kl_err "push: kronicle-lite orient failed (exit $1); failing open"; fi
}

cc_kl_backoff() {  # 0 while inside the 60 s failure back-off
  [[ -s "$CC_KL_S.fail" ]] || return 1
  local t now; IFS= read -r t < "$CC_KL_S.fail" || t=0
  cc_epoch_now_var now
  if [[ "$t" =~ ^[0-9]+$ ]] && (( now - t < 60 )); then CC_KL_FAILED=1; cc_kl_down; return 0; fi
  return 1
}

# cc_kl_init — start this session's cursor at the current head (silent).
cc_kl_init() {
  cc_kl_backoff && return 1
  local pre="$CC_KL_B.stamp.$$" out rc cur seq
  cc_kl_prestamp "$pre" || return 1
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  IFS=$'\x1f' read -r cur seq < <(jq -r '[(.cursor // ""), ((.head.seq // "") | tostring)] | join("\u001f")' <<<"$out" 2>/dev/null)
  if [[ -z "$cur" ]]; then rm -f "$pre"; cc_kl_fail 2; return 1; fi
  cc_kl_pending_note "$out"
  printf '%s\n' "$cur" > "$CC_KL_B.cursor" && printf '%s\n' "$seq" > "$CC_KL_B.seq" && mv -f "$pre" "$CC_KL_B.stamp"
  rm -f "$pre" "$CC_KL_S.fail" 2>/dev/null
  cc_kl_up
  return 0
}

# The stamp is touched just BEFORE a read of the chain and holds that
# moment's epoch second, for the tie rule below.
cc_kl_prestamp() {  # <file>
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$1" 2>/dev/null
}

# Compare two files' mtimes the way `test` sees them: echo older|newer|tie.
# bash 3.2 (macOS /bin/bash) compares whole seconds; bash >= 5.1 uses the
# filesystem's precision. CC_ANCHOR_TEST_MTIME_SECONDS=1 forces the 1-second
# view on any host (tests), via date -r (GNU and BSD).
cc_mtime_cmp() {  # <a> <b>
  if [[ "${CC_ANCHOR_TEST_MTIME_SECONDS:-0}" == 1 ]]; then
    local x y; x="$(date -r "$1" +%s 2>/dev/null)"; y="$(date -r "$2" +%s 2>/dev/null)"
    if (( x < y )); then echo older; elif (( x > y )); then echo newer; else echo tie; fi
    return 0
  fi
  if [[ "$1" -ot "$2" ]]; then echo older; elif [[ "$1" -nt "$2" ]]; then echo newer; else echo tie; fi
}

# cc_kl_unchanged [strict] — 0 when the store cannot have changed since the
# stamp. Hot path: builtin `-ot` tests, no process.
#   older than the stamp  -> unchanged
#   newer than the stamp  -> changed
#   a tie at `test`'s granularity (1 s with bash 3.2, the macOS default):
#     the store was written in the same second as our last read. Re-reading
#     on every tie made every tool call in that second spawn kronicle-lite
#     (macOS CI). Instead one `find -newer` settles it at the filesystem's
#     own precision (ns on APFS / ext4): stamp newer -> unchanged, store
#     newer -> changed. Only a tie even there (1-s filesystem, or one kernel
#     tick) stays ambiguous: the pulse (`strict`, before a world-changing
#     command) re-reads; the push re-reads once the clock has left the
#     stamp's second, so a store write costs at most one extra read and a
#     write landing in that same second right after our read reaches the
#     agent at its next tool call in a later second.
cc_kl_unchanged() {
  [[ -e "$CC_KL_B.stamp" ]] || return 1
  local db="${CC_KL_DD:-${KRONICLE_LITE_DATA_DIR:-$HOME/.kronicle-lite}}/kronicle-lite.db" f c
  local -a tied=()
  [[ -e "$db" ]] || return 1
  for f in "$db" "$db-wal"; do
    [[ -e "$f" ]] || continue
    if [[ "${CC_ANCHOR_TEST_MTIME_SECONDS:-0}" != 1 ]]; then
      [[ "$f" -ot "$CC_KL_B.stamp" ]] && continue
      [[ "$f" -nt "$CC_KL_B.stamp" ]] && return 1
    else
      c="$(cc_mtime_cmp "$f" "$CC_KL_B.stamp")"
      [[ "$c" == older ]] && continue
      [[ "$c" == newer ]] && return 1
    fi
    tied+=("$f")
  done
  (( ${#tied[@]} == 0 )) && return 0
  local equal=0
  for f in "${tied[@]}"; do
    if [[ -n "$(find "$CC_KL_B.stamp" -newer "$f" -print 2>/dev/null)" ]]; then continue
    elif [[ -n "$(find "$f" -newer "$CC_KL_B.stamp" -print 2>/dev/null)" ]]; then return 1
    else equal=1; fi
  done
  (( equal )) || return 0
  [[ "${1:-}" == strict ]] && return 1
  local t="" now; IFS= read -r t < "$CC_KL_B.stamp" || true
  [[ "$t" =~ ^[0-9]+$ ]] || return 1
  cc_epoch_now_var now
  (( now <= t ))
}

# cc_kl_fetch — new retractions since this session's cursor. Returns 0 when
# the head moved and the retractions were fetched (KL_SHOWN may still be 0),
# 1 when nothing changed, the CLI failed (fail open) or no cursor existed yet.
# Sets KL_BODY ("- …" lines), KL_SHOWN, KL_BLOCK, KL_COS, KL_SEQ.
cc_kl_fetch() {  # [strict] — see cc_kl_unchanged
  KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0; KL_SEQ=""
  if [[ ! -s "$CC_KL_B.cursor" ]]; then
    # Main agent without a cursor: start at the head (nothing is "new" yet).
    # Subagent without one (no SubagentStart seen): seed from the parent and
    # go on to fetch, so what the parent has not consumed reaches it too.
    if [[ -z "$CC_KL_AGENT" || ! -s "$CC_KL_S.cursor" ]]; then cc_kl_init || CC_KL_FAILED=1; return 1; fi
    cc_kl_seed || { CC_KL_FAILED=1; return 1; }
  fi
  # Parked at a corrupt head and the store has since been found ok (by any
  # agent of the session): re-read from the unmoved cursor.
  if [[ -e "$CC_KL_B.parked" && ! -e "$CC_KL_S.integrity" ]]; then rm -f "$CC_KL_B.parked" "$CC_KL_B.seq" "$CC_KL_B.stamp" 2>/dev/null; fi
  cc_kl_unchanged "${1:-}" && return 1
  cc_kl_backoff && return 1
  local pre="$CC_KL_B.stamp.$$" out rc seq stored="" cur=""
  cc_kl_prestamp "$pre" || return 1
  out="$(cc_kl_orient --focus pulse)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  seq="$(jq -r '.head.seq // empty' <<<"$out" 2>/dev/null)"
  if [[ -z "$seq" ]]; then rm -f "$pre"; cc_kl_fail 3; return 1; fi
  cc_kl_integrity_from "$out" || true
  cc_kl_pending_note "$out"
  [[ -s "$CC_KL_B.seq" ]] && IFS= read -r stored < "$CC_KL_B.seq"
  if [[ -n "$seq" && "$seq" == "$stored" ]]; then mv -f "$pre" "$CC_KL_B.stamp"; cc_kl_up; return 1; fi
  IFS= read -r cur < "$CC_KL_B.cursor"
  out="$(cc_kl_orient --cursor "$cur" --focus retractions)"; rc=$?
  if (( rc != 0 )) || [[ -z "$out" ]]; then rm -f "$pre"; cc_kl_fail "$rc"; return 1; fi
  cc_kl_pending_note "$out"
  local sc=0; cc_on push_cosmetic 0 && sc=1
  local parsed
  parsed="$(jq -r --arg show_cosmetic "$sc" -f "$CC_LIB_DIR/retractions.jq" <<<"$out" 2>/dev/null)" || { rm -f "$pre"; cc_kl_fail 3; return 1; }
  local ncur counts rest integ
  ncur="${parsed%%$'\n'*}"; rest="${parsed#*$'\n'}"
  KL_SEQ="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  counts="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  integ="${rest%%$'\n'*}"
  if [[ "$rest" == *$'\n'* ]]; then KL_BODY="${rest#*$'\n'}"; else KL_BODY=""; fi
  if [[ "$integ" == fail* ]]; then
    # The store says it is corrupt: deliver no retractions from it and keep
    # the cursor where it was (after a repair they are re-read from there);
    # remember the head so the next calls do not re-read it each time.
    local iseq iprob; IFS=$'\x1f' read -r _ iseq iprob <<<"$integ"
    cc_kl_integrity_note "$iseq" "$iprob"
    printf '%s\n' "$KL_SEQ" > "$CC_KL_B.seq"
    : > "$CC_KL_B.parked"
    KL_BODY=""; KL_SHOWN=0; KL_BLOCK=0; KL_COS=0
    mv -f "$pre" "$CC_KL_B.stamp"; rm -f "$CC_KL_S.fail" 2>/dev/null
    cc_kl_up
    return 0
  fi
  cc_kl_integrity_note ok
  read -r KL_SHOWN KL_BLOCK KL_COS <<<"$counts"
  [[ "$KL_SHOWN" =~ ^[0-9]+$ ]] || KL_SHOWN=0
  [[ "$KL_BLOCK" =~ ^[0-9]+$ ]] || KL_BLOCK=0
  [[ "$KL_COS" =~ ^[0-9]+$ ]] || KL_COS=0
  if [[ -n "$ncur" ]]; then
    printf '%s\n' "$ncur" > "$CC_KL_B.cursor.$$" && mv -f "$CC_KL_B.cursor.$$" "$CC_KL_B.cursor"
    printf '%s\n' "$KL_SEQ" > "$CC_KL_B.seq"
  fi
  mv -f "$pre" "$CC_KL_B.stamp"
  rm -f "$CC_KL_S.fail" 2>/dev/null
  cc_kl_up
  return 0
}

cc_kl_integrity_text() {
  local s="?" p="integrity check failed"
  [[ -s "$CC_KL_S.integrity" ]] && IFS=$'\x1f' read -r s p < "$CC_KL_S.integrity"
  printf '%s' "cc-anchor: kronicle-lite STORE INTEGRITY FAILURE at seq ${s}: ${p}. The chain is corrupt or was tampered with: do not act on runbooks, notes or anything else recalled from kronicle-lite until it is resolved (kronicle-lite verify-chain / doctor; tell the operator). The cc-anchor pulse blocks world-changing commands meanwhile (unless pulse_mode is warn)."
}

# cc_kl_integrity_recheck — re-read integrity now (bypassing the mtime gate):
# 0 while the store still reports a failure (or cannot be read), 1 once ok.
cc_kl_integrity_recheck() {
  local cur="" out rc
  [[ -s "$CC_KL_B.cursor" ]] && IFS= read -r cur < "$CC_KL_B.cursor"
  local -a c=(); [[ -n "$cur" ]] && c=(--cursor "$cur")
  out="$(cc_kl_orient ${c[@]+"${c[@]}"} --focus retractions)"; rc=$?
  (( rc == 0 )) && [[ -n "$out" ]] || return 0
  cc_kl_pending_note "$out"
  cc_kl_integrity_from "$out" && return 0
  [[ -e "$CC_KL_S.integrity" ]] && return 0
  # Repaired: forget the head we parked at, so the next fetch re-reads the
  # retractions since the (unmoved) cursor.
  rm -f "$CC_KL_B.seq" "$CC_KL_B.stamp" "$CC_KL_B.intwarned" "$CC_KL_B.parked" 2>/dev/null
  return 1
}

# cc_kl_push <PostToolUse payload> — sets CC_KL_CONTEXT (empty: say nothing).
CC_KL_CONTEXT=""
cc_kl_push() {
  local payload="$1" sid=""
  CC_KL_CONTEXT=""
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_kl_session "$sid" "$(cc_payload_agent "$payload")"
  [[ -e "$CC_KL_S.off" ]] && return 0
  cc_kl_enabled || return 0
  # The agent named its own kronicle-lite actor in a tool call: its pending
  # list is that actor's (per agent: a subagent may use its own actor_id).
  if [[ "$payload" =~ \"tool_name\":[[:space:]]*\"mcp__[^\"]*kronicle[^\"]*\" && "$payload" == *'"actor_id"'* ]]; then
    local na; na="$(jq -r '.tool_input.actor_id // empty | tostring' <<<"$payload" 2>/dev/null)"
    if [[ -n "$na" && "$na" != "$(cc_kl_agent_actor)" ]]; then printf '%s\n' "$na" > "$CC_KL_B.actor" 2>/dev/null; rm -f "$CC_KL_B.klpend" "$CC_KL_B.stamp" 2>/dev/null; fi
  fi
  # The agent got a tool call in since the last push: what it was told is no
  # longer "unacted on".
  [[ -e "$CC_KL_B.pending" ]] && rm -f "$CC_KL_B.pending"
  cc_kl_fetch || true
  # Top priority: a store that says it is corrupt (once per distinct problem).
  local warn=""
  if [[ -s "$CC_KL_S.integrity" ]]; then
    local key="" seen=""; IFS= read -r key < "$CC_KL_S.integrity"
    [[ -s "$CC_KL_B.intwarned" ]] && IFS= read -r seen < "$CC_KL_B.intwarned"
    if [[ "$key" != "$seen" ]]; then
      printf '%s\n' "$key" > "$CC_KL_B.intwarned" 2>/dev/null || true
      warn="$(cc_kl_integrity_text)"
    fi
  fi
  # A feed that has been unreadable for push_offline_after consecutive calls.
  local after n=0; after="$(cc_cfg_raw push_offline_after)"; [[ "$after" =~ ^[0-9]+$ ]] || after=20
  [[ -s "$CC_KL_S.down" ]] && IFS= read -r n < "$CC_KL_S.down"
  if [[ "$n" =~ ^[0-9]+$ ]] && (( after > 0 && n >= after )) && [[ ! -e "$CC_KL_S.downwarned" ]]; then
    : > "$CC_KL_S.downwarned"
    cc_log "push: retraction feed offline for ${n} consecutive calls; advised the agent once"
    warn="${warn:+$warn

}cc-anchor: the kronicle-lite retraction feed has been offline for ${n} consecutive tool calls (the CLI is missing, failing or timing out; see .claude/cc-anchor/log). Changes to runbooks and notes are NOT being pushed to you right now: re-read the source (get_system_state with your cursor, recall) yourself before any world-changing command."
  fi
  # Delivered is not reconciled (kronicle-lite >= 0.8.0 `pending`): a change
  # the agent still has not re-read push_reminder_after (15) tool calls after
  # it became pending, with no world-changing command attempted meanwhile
  # (the pulse would have shown it), gets ONE reminder line.
  local pc; pc="$(cc_kl_pending_count)"
  if [[ "$pc" =~ ^[0-9]+$ ]] && (( pc > 0 )); then
    local k=0 ra; [[ -s "$CC_KL_B.pendcalls" ]] && IFS= read -r k < "$CC_KL_B.pendcalls"
    [[ "$k" =~ ^[0-9]+$ ]] || k=0; k=$((k + 1)); printf '%s\n' "$k" > "$CC_KL_B.pendcalls"
    ra="$(cc_cfg_raw push_reminder_after)"; [[ "$ra" =~ ^[0-9]+$ ]] || ra=15
    if (( ra > 0 && k >= ra )) && [[ ! -e "$CC_KL_B.reminded" && ! -e "$CC_KL_B.wcattempt" ]]; then
      : > "$CC_KL_B.reminded"
      local head="" slugs="" act=""; IFS= read -r head < "$CC_KL_B.klpend"
      IFS=$'\x1f' read -r _ _ act slugs <<<"$head"
      cc_log "push: pending reminder (${pc} item(s), actor ${act}) after ${k} tool calls"
      warn="${warn:+$warn

}cc-anchor: reminder — ${pc} kronicle-lite change(s) you relied on are still not re-read at their current version (${slugs:-see kronicle-lite pending --actor ${act}}). Receiving them earlier does not count: re-read (recall, or kronicle://docs/<slug>) before acting on them."
    fi
  elif [[ -e "$CC_KL_B.pendcalls" || -e "$CC_KL_B.reminded" || -e "$CC_KL_B.wcattempt" ]]; then
    rm -f "$CC_KL_B.pendcalls" "$CC_KL_B.reminded" "$CC_KL_B.wcattempt" 2>/dev/null
  fi
  if (( KL_SHOWN == 0 )); then CC_KL_CONTEXT="$warn"; return 0; fi
  CC_KL_CONTEXT="${warn:+$warn

}cc-anchor: kronicle-lite changed while you were working — ${KL_SHOWN} retraction(s) since your last check (head seq ${KL_SEQ}). Anything you read before this may be stale:
${KL_BODY}
Re-read the affected document (recall, or get_system_state with your cursor) and use the current text before you act on it."
  if (( KL_COS > 0 )) && ! cc_on push_cosmetic 0; then CC_KL_CONTEXT="${CC_KL_CONTEXT} (${KL_COS} cosmetic edit(s) not shown.)"; fi
  (( KL_BLOCK > 0 )) && printf '%s\n' "$KL_BODY" > "$CC_KL_B.pending"
  cc_log "push: ${KL_SHOWN} retraction(s) (${KL_BLOCK} blocking, ${KL_COS} cosmetic) at seq ${KL_SEQ}"
  return 0
}

# ═══════════════════ 0.5.0: Bash claimed-path guard (sea-lite) ═══════════════════
#
# The Edit/Write scope guard never sees `sed -i`, redirects, formatters or
# codegen run through Bash, and sea-lite's pre-commit guard only fires at
# commit time. So after every Bash call: did it change a path inside a live
# sea-lite claim held by ANOTHER session? If so, say so right away
# (PostToolUse additionalContext) naming the path, the holder, the ticket and
# the expiry. Advisory: the change already happened; the agent undoes it or
# coordinates.
#
#   PreToolUse(Bash)  (pulse.sh) writes <run>/bashguard/<sid8>.pre.<tool_use_id>
#                     — one stamp PER CALL, so overlapping Bash calls of one
#                     session (parallel tool calls, subagents) don't clobber
#                     each other; its mtime is "this call began".
#   PostToolUse(Bash) that call's stamp + the claims other sessions hold (a
#                     cached `sea-lite board --json`; refreshed when older than
#                     bash_guard_ttl s, when the sea-lite store file changed
#                     since the cache was filled, or after any sea_* result).
#                     No foreign claim => no process. Otherwise ONE
#                     `find <claimed paths> -newer|-cnewer <stamp>`: change time
#                     as well as modification time, so mtime-preserving writes
#                     (cp -p / -a, tar -x, mv over a file, touch -r) count. A
#                     find that times out falls back to `git status` over the
#                     claimed paths. A hit costs one `git status` to drop
#                     git-ignored output before warning.
#
# Switch `bash_guard`: on | off | auto (default: on when this project has seen
# sea-lite claims or sea-lite is configured), resolved once per session.
# Fail-open: no CLI / timeout / bad output => no warning, one log line.

CC_BG_CONTEXT=""

cc_bg_session() {  # <session_id> — CC_BG_B (per-session prefix), CC_BG_D (dir)
  local s="${1:-nosession}"; s="${s//[^A-Za-z0-9]/}"; s="${s:0:8}"
  CC_BG_D="$CC_RUN/bashguard"; CC_BG_B="$CC_BG_D/${s:-nosession}"
}

cc_bg_enabled() {
  [[ -e "$CC_BG_B.on" ]] && return 0
  [[ -e "$CC_BG_B.off" ]] && return 1
  mkdir -p "$CC_BG_D" 2>/dev/null || return 1
  case "$(cc_cfg_raw bash_guard)" in
    0|false|no|off) : > "$CC_BG_B.off"; return 1;;
    1|true|yes|on) ;;
    *) if [[ ! -s "$CC_CLAIMS" ]] && ! cc_sea_configured; then : > "$CC_BG_B.off"; return 1; fi;;
  esac
  if ! cc_find_cli sea-lite >/dev/null; then
    : > "$CC_BG_B.off"
    cc_log_once bg_nobin "bash_guard: sea-lite CLI not found; Bash-changed paths are not checked against claims"
    return 1
  fi
  : > "$CC_BG_B.on"
}

cc_bg_tid() {  # <payload> — sanitized tool_use_id ("" when absent)
  local t=""
  [[ "$1" =~ \"tool_use_id\":[[:space:]]*\"([^\"]*)\" ]] && t="${BASH_REMATCH[1]}"
  t="${t//[^A-Za-z0-9_-]/}"; printf '%s' "${t:0:64}"
}

# PreToolUse(Bash): stamp the start of THIS call (one builtin write).
cc_bg_prestamp() {  # <payload>
  local payload="$1" sid="" tid
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_bg_session "$sid"
  [[ -e "$CC_BG_B.off" ]] && return 0
  tid="$(cc_bg_tid "$payload")"
  [[ -n "$tid" ]] || return 0
  [[ -d "$CC_BG_D" ]] || mkdir -p "$CC_BG_D" 2>/dev/null || return 0
  : > "$CC_BG_B.pre.$tid" 2>/dev/null || true
}

cc_bg_seadb() { printf '%s' "${CC_ANCHOR_SEA_DATA_DIR:-${KRONICLE_LITE_DATA_DIR:-$HOME/.kronicle-lite}}/kronicle-lite.db"; }

# Refresh <dir>/claims.tsv from `sea-lite board --json`: one line per live
# claimed scope: session \x1f absolute path \x1f holder \x1f ticket \x1f title \x1f expires
cc_bg_refresh() {
  local now; cc_epoch_now_var now
  printf '%s\n' "$now" > "$CC_BG_D/claims.at" 2>/dev/null || return 1
  # Drop per-call stamps whose PostToolUse never came (older than 10 min).
  find "$CC_BG_D" -maxdepth 1 -name '*.pre.*' -mmin +10 -exec rm -f {} + 2>/dev/null || true
  local bin to out rc
  bin="$(cc_find_cli sea-lite)" || { : > "$CC_BG_D/claims.tsv"; return 1; }
  to="$(cc_cfg_raw scope_timeout)"; [[ "$to" =~ ^[0-9]+$ ]] || to=4
  local -a args=(board --json)
  [[ -n "${CC_ANCHOR_SEA_DATA_DIR:-}" ]] && args+=(--data-dir "$CC_ANCHOR_SEA_DATA_DIR")
  if [[ "$bin" == *.js || "$bin" == *.mjs ]]; then out="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout "$to" node "$bin" "${args[@]}" 2>/dev/null)"; rc=$?
  else out="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout "$to" "$bin" "${args[@]}" 2>/dev/null)"; rc=$?; fi
  # The board call itself may write the store: stamp the cache AFTER it, so
  # only a later write (a new claim by anyone) looks newer.
  : > "$CC_BG_D/claims.stamp" 2>/dev/null || true
  if (( rc != 0 )) || [[ -z "$out" ]]; then
    : > "$CC_BG_D/claims.tsv"
    cc_log_once bg_board "bash_guard: sea-lite board failed (exit $rc); not checking until the next refresh"
    return 1
  fi
  jq -r '.tickets[]? | select(.claim != null) | . as $t | .claim as $c
    | ($t.project // "") as $p
    | ($c.scope // [])[]
    | sub("[*?\\[].*$"; "") | sub("/+$"; "")
    | [($c.session // ""), (if startswith("/") then . elif . == "" then $p else $p + "/" + . end),
       ($c.holder_label // $c.holder // "?"), ($t.id // "" | .[0:8]), ($t.title // "" | gsub("[\\x1f\\n]"; " ") | .[0:80]), ($c.expires_at // "")]
    | join("\u001f")' <<<"$out" > "$CC_BG_D/claims.tsv.$$" 2>/dev/null && mv -f "$CC_BG_D/claims.tsv.$$" "$CC_BG_D/claims.tsv"
}

# 0 when the claims cache must be refreshed (builtins only).
cc_bg_stale() {
  [[ -e "$CC_BG_D/claims.tsv" && -e "$CC_BG_D/claims.stamp" ]] || return 0
  local ttl at=0 now; ttl="$(cc_cfg_raw bash_guard_ttl)"; [[ "$ttl" =~ ^[0-9]+$ ]] || ttl=30
  cc_epoch_now_var now
  [[ -s "$CC_BG_D/claims.at" ]] && IFS= read -r at < "$CC_BG_D/claims.at"
  [[ "$at" =~ ^[0-9]+$ ]] || at=0
  (( now - at >= ttl )) && return 0
  local db; db="$(cc_bg_seadb)"
  [[ -e "$db" && "$db" -nt "$CC_BG_D/claims.stamp" ]] && return 0
  [[ -e "$db-wal" && "$db-wal" -nt "$CC_BG_D/claims.stamp" ]] && return 0
  return 1
}

# PostToolUse(Bash): sets CC_BG_CONTEXT (empty: say nothing).
cc_bg_check() {
  local payload="$1" sid="" tid pre
  CC_BG_CONTEXT=""
  [[ "$payload" =~ \"tool_name\":[[:space:]]*\"Bash\" ]] || return 0
  [[ "$payload" =~ \"session_id\":[[:space:]]*\"([^\"]*)\" ]] && sid="${BASH_REMATCH[1]}"
  cc_bg_session "$sid"
  [[ -e "$CC_BG_B.off" ]] && return 0
  cc_bg_enabled || return 0
  tid="$(cc_bg_tid "$payload")"
  [[ -n "$tid" ]] || return 0
  pre="$CC_BG_B.pre.$tid"
  [[ -e "$pre" ]] || return 0
  if cc_bg_stale; then cc_bg_refresh || true; fi
  [[ -s "$CC_BG_D/claims.tsv" ]] || return 0
  local me ov; me="$sid"; ov="$(cc_cfg_raw sea_session)"; [[ -n "$ov" ]] && me="$ov"
  local iso; cc_now_var iso
  local ses path holder ticket title exp
  local -a cl=() paths=() gone=()
  while IFS=$'\x1f' read -r ses path holder ticket title exp; do
    [[ -n "$path" && "$ses" != "$me" ]] || continue
    [[ -z "$exp" || "$exp" > "$iso" ]] || continue
    cl+=("${path}"$'\x1f'"${holder}"$'\x1f'"${ticket}"$'\x1f'"${title}"$'\x1f'"${exp}")
    if [[ -e "$path" || -L "$path" ]]; then paths+=("$path")
    elif [[ -d "${path%/*}" ]] && ! [[ "${path%/*}" -ot "$pre" ]]; then gone+=("$path (removed)"); fi
  done < "$CC_BG_D/claims.tsv"
  (( ${#cl[@]} > 0 )) || { rm -f "$pre" 2>/dev/null; return 0; }
  # One find over the claimed paths: modified OR status-changed after the stamp.
  local hits="" rc=0 note=""
  if (( ${#paths[@]} > 0 )); then
    hits="$(cc_with_timeout 5 find "${paths[@]}" \( -name .git -o -name node_modules \) -prune -o \( -newer "$pre" -o -cnewer "$pre" \) -print 2>/dev/null)"; rc=$?
    if (( rc == 124 )); then
      # Too big to scan in time: what git says changed under those paths
      # (cannot tell this call's changes from earlier ones; say so).
      note=" (find timed out; per git status — may include earlier changes)"
      local -a rel=() p
      for p in "${paths[@]}"; do rel+=("${p#"$CC_ROOT"/}"); done
      hits="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 5 git status --porcelain -- "${rel[@]}" 2>/dev/null | while IFS= read -r p; do p="${p:3}"; p="${p#*-> }"; printf '%s\n' "$CC_ROOT/$p"; done)"
      cc_log_once bg_find_timeout "bash_guard: find over claimed paths timed out; fell back to git status"
    fi
  fi
  rm -f "$pre" 2>/dev/null
  local -a found=() h
  if [[ -n "$hits" ]]; then
    local -a all=()
    while IFS= read -r h; do [[ -n "$h" ]] && all+=("${h%/}"); done <<<"$hits"
    # A directory whose entries changed is reported only when nothing inside
    # it was (an entry was removed or renamed away).
    for h in "${all[@]}"; do
      if [[ -d "$h" && ! -L "$h" ]]; then
        local inner=0 o
        for o in "${all[@]}"; do [[ "$o" == "$h/"* ]] && { inner=1; break; }; done
        (( inner )) && continue
        found+=("$h/ (entries added, removed or renamed)")
      else found+=("$h"); fi
    done
  fi
  found+=(${gone[@]+"${gone[@]}"})
  (( ${#found[@]} > 0 )) || return 0
  # Drop git-ignored files (build output) with one bounded `git status`.
  local ignored=""
  if command -v git >/dev/null 2>&1; then
    local -a gp=() l
    for l in "${found[@]}"; do l="${l% (entries added, removed or renamed)}"; l="${l% (removed)}"; gp+=("${l%/}"); done
    ignored="$(cd "$CC_ROOT" 2>/dev/null && cc_with_timeout 3 git status --porcelain --ignored=matching -- "${gp[@]}" 2>/dev/null | while IFS= read -r l; do [[ "$l" == '!! '* ]] && printf '%s\n' "${l#!! }"; done)"
  fi
  local out="" n=0 shown=0 rel l2 c cpath bare
  for h in "${found[@]}"; do
    bare="${h% (entries added, removed or renamed)}"; bare="${bare% (removed)}"; bare="${bare%/}"
    rel="${h#"$CC_ROOT"/}"
    if [[ -n "$ignored" ]]; then
      local skip=0 ig
      while IFS= read -r ig; do [[ -n "$ig" && ( "${bare#"$CC_ROOT"/}" == "${ig%/}" || "${bare#"$CC_ROOT"/}" == "${ig%/}"/* ) ]] && { skip=1; break; }; done <<<"$ignored"
      (( skip )) && continue
    fi
    # Which claim covers it (first match).
    holder="?"; ticket="?"; title=""; exp=""; cpath=""
    for c in "${cl[@]}"; do
      IFS=$'\x1f' read -r path holder ticket title exp <<<"$c"
      if [[ "$bare" == "$path" || "$bare" == "$path/"* ]]; then cpath="$path"; break; fi
    done
    [[ -n "$cpath" ]] || continue
    n=$((n + 1))
    (( shown < 10 )) || continue
    shown=$((shown + 1))
    l2="${cpath#"$CC_ROOT"/}"
    out="${out}
- ${rel} — held by ${holder}, ticket ${ticket} \"${title}\" (locks ${l2}; expires ${exp:-?})"
  done
  (( n > 0 )) || return 0
  (( n > shown )) && out="${out}
- … and $((n - shown)) more"
  CC_BG_CONTEXT="cc-anchor bash guard: that Bash call changed ${n} path(s) inside live sea-lite claims held by OTHER sessions${note}:${out}
Those paths are another agent's work in progress. Undo your change (git checkout -- <path>, or delete the new file) unless you agreed it with the holder; the Edit/Write scope guard does not see Bash edits."
  cc_log "bash_guard: ${n} path(s) inside other sessions' claims after Bash"
  return 0
}
