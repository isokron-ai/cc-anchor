#!/usr/bin/env bash
# cc-anchor — shared shell library sourced by every hook and the statusline.
#
# Design rules (all hooks must honor them):
#   * FAIL-OPEN: never block Claude Code. Any error path => `return 0` /
#     `exit 0` with nothing on stdout (stdout is parsed as hook JSON).
#   * FAST: PostToolUse runs on every tool call. bash builtins + ONE jq
#     (render.jq) + one mv. No node, no cksum, no date when bash >= 4.2.
#   * ONE RENDERER: scripts/render.jq owns the card layout. lib.sh only
#     feeds it files and writes its four outputs back. scripts/anchor.mjs
#     edits the hand-written top and calls cc_render for the rest.
#
# Card layout (<= 25 lines, enforced by render.jq):
#
#   # ANCHOR — <project name>                       ─┐
#   <!-- cc-anchor v1 … -->                          │ hand-edited "top"
#   Project: …                                       │ (copied verbatim,
#   Goal: …                                          │  never rewritten)
#   Invariants:                                      │
#   - never …                                       ─┘
#   <!-- cc-anchor:trail -->                         ← marker (CC_MARKER)
#   Trail (last N tool calls, newest first):        ─┐
#   - <iso> <tool> <target>                          │ generated by
#   Cursor: <token>            (only when found)     │ render.jq
#   Compacted: <iso|never>                           │
#   Refreshed: <iso|never>                          ─┘
#
# shellcheck disable=SC2034  # CC_* globals are consumed by the sourcing scripts

# Claude Code spawns hooks with a minimal PATH on some hosts (Homebrew
# node/jq live outside it). Harmless elsewhere.
export PATH="/opt/homebrew/bin:/usr/local/bin:${PATH}"
export TZ=UTC

CC_LIB_DIR="${BASH_SOURCE[0]%/*}"; [[ "$CC_LIB_DIR" == "${BASH_SOURCE[0]}" ]] && CC_LIB_DIR=.
CC_RENDER_JQ="$CC_LIB_DIR/render.jq"
CC_MARKER='<!-- cc-anchor:trail -->'
CC_VERSION_LINE='<!-- cc-anchor v1 — edit the lines above the trail marker by hand or with /cc-anchor:anchor. Everything below the marker is regenerated. -->'
CC_TRAIL_N="${CC_ANCHOR_TRAIL_N:-5}"
CC_LOG_KEEP=200          # rolling trail: trim back to this many lines…
CC_LOG_TRIM_AT=400       # …whenever it grows past this (off the hot path).
CC_DRIFT_WARN_MIN="${CC_ANCHOR_DRIFT_WARN_MIN:-45}"
CC_CURSOR_RE='^sxt1c?\.[A-Za-z0-9_.-]+$'

# ISO-8601 UTC "now". bash >= 4.2 has a printf builtin for strftime (no
# fork); older bash (macOS stock 3.2) falls back to date(1).
# cc_now_var NAME sets $NAME without a subshell; cc_now echoes it.
cc_now_var() {
  local __cc_t
  if printf -v __cc_t '%(%Y-%m-%dT%H:%M:%SZ)T' -1 2>/dev/null && [[ "$__cc_t" == 20* ]]; then printf -v "$1" '%s' "$__cc_t"
  else printf -v "$1" '%s' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"; fi
}
cc_now() { local __cc_n; cc_now_var __cc_n; printf '%s' "$__cc_n"; }

cc_have_jq() { command -v jq >/dev/null 2>&1; }

# Short stable hash of a string (home-fallback directory name). Mirrors
# resolvePaths() in anchor.mjs (sha1, first 12 hex chars).
cc_hash() {
  if command -v sha1sum >/dev/null 2>&1; then printf '%s' "$1" | sha1sum | cut -c1-12
  elif command -v shasum >/dev/null 2>&1; then printf '%s' "$1" | shasum | cut -c1-12
  else printf '%s' "$1" | cksum | cut -d' ' -f1
  fi
}

# cc_resolve [root] — populate CC_ROOT, CC_DIR (card dir), CC_CARD,
# CC_RUN (runtime dir: trail + state + cursor), CC_TRAIL, CC_STATE, CC_WHERE.
#
# Root precedence: explicit arg > $CLAUDE_PROJECT_DIR > $PWD.
# Storage: $CC_ANCHOR_DIR if set; else <root>/.claude when the root is a
# real project (has .claude/ or .git); else ~/.claude/cc-anchor/<hash>/.
cc_resolve() {
  local root="${1:-${CLAUDE_PROJECT_DIR:-$PWD}}"
  root="${root%/}"
  CC_ROOT="$root"
  if [[ -n "${CC_ANCHOR_DIR:-}" ]]; then
    CC_DIR="${CC_ANCHOR_DIR%/}"; CC_RUN="$CC_DIR/cc-anchor"; CC_WHERE="env"
  elif [[ "${CC_ANCHOR_HOME:-0}" != "1" && ( -d "$root/.claude" || -e "$root/.git" ) ]]; then
    CC_DIR="$root/.claude"; CC_RUN="$CC_DIR/cc-anchor"; CC_WHERE="project"
  else
    CC_DIR="${HOME}/.claude/cc-anchor/$(cc_hash "$root")"; CC_RUN="$CC_DIR"; CC_WHERE="home"
  fi
  CC_CARD="$CC_DIR/anchor.md"
  CC_TRAIL="$CC_RUN/trail.jsonl"
  CC_STATE="$CC_RUN/state.json"
  CC_CURSOR_FILE="$CC_RUN/cursor"
}

cc_ensure_dirs() { [[ -d "$CC_RUN" ]] || mkdir -p "$CC_RUN" 2>/dev/null || return 1; }

# ── state.json ──────────────────────────────────────────────────────────
cc_state_get() {  # key
  [[ -s "$CC_STATE" ]] || { echo ""; return 0; }
  jq -r --arg k "$1" '.[$k] // empty' "$CC_STATE" 2>/dev/null || echo ""
}

cc_state_set() {  # key value [key value …]
  cc_ensure_dirs || return 0
  local cur='{}'
  [[ -s "$CC_STATE" ]] && cur="$(cat "$CC_STATE" 2>/dev/null || echo '{}')"
  local args=() filter='.' i=0
  while [[ $# -ge 2 ]]; do
    args+=(--arg "k$i" "$1" --arg "v$i" "$2")
    filter="$filter | .[\$k$i] = \$v$i"
    shift 2; i=$((i+1))
  done
  local out
  out="$(jq -c "${args[@]}" "$filter" <<<"$cur" 2>/dev/null)" || out="$(jq -nc "${args[@]}" "{} $filter" 2>/dev/null)" || return 0
  printf '%s\n' "$out" > "$CC_STATE.tmp.$$" && mv -f "$CC_STATE.tmp.$$" "$CC_STATE"
}

# ── card helpers (read side) ────────────────────────────────────────────
# Hand-edited top: everything before the marker (whole file if no marker).
cc_card_top() {
  [[ -s "$CC_CARD" ]] || return 0
  local line
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ "$line" == "$CC_MARKER" ]] && break
    printf '%s\n' "$line"
  done < "$CC_CARD"
}

# Goal line with the "Goal:" prefix stripped ("" when absent).
cc_card_goal() {
  local line
  while IFS= read -r line; do
    if [[ "$line" == Goal:* ]]; then line="${line#Goal:}"; printf '%s' "${line#"${line%%[![:space:]]*}"}"; return 0; fi
  done < <(cc_card_top)
}

cc_valid_cursor() { [[ "$1" =~ $CC_CURSOR_RE ]]; }

# Echo the first valid cursor found, searching (in order):
#   <run>/cursor              — captured by our PostToolUse hook
#   <root>/.cc-anchor-cursor  — hand-managed, plain token or JSON
#   <root>/.sextant-cursor    — IsoKron breadcrumb JSON {cursor_token}
#   <root>/.kronicle-cursor   — kronicle-lite orient skill convention
# Sets CC_CURSOR_SRC to the file that matched.
cc_detect_cursor() {
  local f tok first
  CC_CURSOR_SRC=""
  for f in "$CC_CURSOR_FILE" "$CC_ROOT/.cc-anchor-cursor" "$CC_ROOT/.sextant-cursor" "$CC_ROOT/.kronicle-cursor"; do
    [[ -s "$f" ]] || continue
    IFS= read -r first < "$f" || true
    tok=""
    if [[ "${first#"${first%%[![:space:]]*}"}" == "{"* ]]; then
      cc_have_jq && tok="$(jq -r '.cursor_token // .cursor_compact // .cursor // empty' "$f" 2>/dev/null)"
    else
      tok="${first//[[:space:]]/}"
    fi
    if [[ -n "$tok" ]] && cc_valid_cursor "$tok"; then CC_CURSOR_SRC="$f"; printf '%s' "$tok"; return 0; fi
  done
  return 1
}

# 0 when a kronicle-lite MCP server (or plugin) is configured for this
# project, 1 otherwise. File-based only: `claude mcp list` spawns servers
# and is far too slow for a hook. Override with CC_ANCHOR_KRONICLE=1|0.
cc_kronicle_configured() {
  case "${CC_ANCHOR_KRONICLE:-}" in 1) return 0;; 0) return 1;; esac
  cc_have_jq || return 1
  local f
  for f in "$CC_ROOT/.mcp.json" "${HOME}/.claude.json"; do
    [[ -s "$f" ]] || continue
    if jq -e --arg root "$CC_ROOT" '
        def hit: tostring | ascii_downcase | test("kronicle");
        def servers: (.mcpServers // {}) + ((.projects // {})[$root].mcpServers // {});
        servers | to_entries | any(.key | hit) or any(.value | ((.command // ""), (.args // [])) | hit)
      ' "$f" >/dev/null 2>&1; then return 0; fi
  done
  for f in "${HOME}/.claude/settings.json" "$CC_ROOT/.claude/settings.json" "$CC_ROOT/.claude/settings.local.json"; do
    [[ -s "$f" ]] || continue
    if jq -e '(.enabledPlugins // {}) | to_entries | any((.key | ascii_downcase | test("^kronicle")) and .value == true)' "$f" >/dev/null 2>&1; then return 0; fi
  done
  return 1
}

# ── render ──────────────────────────────────────────────────────────────
# cc_render [hook-json]
#   Runs render.jq once. With a PostToolUse payload as $1 the breadcrumb is
#   derived, appended to the trail and shown; without it the card is simply
#   regenerated (cursor/compacted/refreshed/trail refreshed from disk).
#   Writes: trail.jsonl (append), <run>/cursor (if captured), state.json,
#   anchor.md (atomic). Silent no-op on any failure.
cc_render() {
  cc_have_jq || return 0
  cc_ensure_dirs || return 0
  [[ -d "$CC_DIR" ]] || mkdir -p "$CC_DIR" 2>/dev/null || return 0
  local payload="${1:-null}"
  local card=/dev/null state=/dev/null c0=/dev/null c1=/dev/null c2=/dev/null c3=/dev/null
  [[ -s "$CC_CARD" ]] && card="$CC_CARD"
  [[ -s "$CC_STATE" ]] && state="$CC_STATE"
  [[ -s "$CC_CURSOR_FILE" ]] && c0="$CC_CURSOR_FILE"
  [[ -s "$CC_ROOT/.cc-anchor-cursor" ]] && c1="$CC_ROOT/.cc-anchor-cursor"
  [[ -s "$CC_ROOT/.sextant-cursor" ]] && c2="$CC_ROOT/.sextant-cursor"
  [[ -s "$CC_ROOT/.kronicle-cursor" ]] && c3="$CC_ROOT/.kronicle-cursor"
  local trail=/dev/null now out
  [[ -s "$CC_TRAIL" ]] && trail="$CC_TRAIL"
  cc_now_var now
  out="$(jq -r -f "$CC_RENDER_JQ" \
    --rawfile card "$card" --rawfile trail "$trail" --slurpfile state "$state" \
    --rawfile c0 "$c0" --rawfile c1 "$c1" --rawfile c2 "$c2" --rawfile c3 "$c3" \
    --arg now "$now" --arg name "${CC_ROOT##*/}" --arg n "$CC_TRAIL_N" --arg root "$CC_ROOT" \
    --arg marker "$CC_MARKER" --arg version "$CC_VERSION_LINE" --arg cursor_re "$CC_CURSOR_RE" \
    <<<"$payload" 2>/dev/null)" || return 0
  [[ -n "$out" ]] || return 0
  # Split the four parts with bash builtins (no further processes).
  local entry captured newstate rest
  entry="${out%%$'\n'*}";   rest="${out#*$'\n'}"
  captured="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  newstate="${rest%%$'\n'*}"; rest="${rest#*$'\n'}"
  [[ -n "$entry" ]] && printf '%s\n' "$entry" >> "$CC_TRAIL"
  [[ -n "$captured" ]] && printf '%s\n' "$captured" > "$CC_CURSOR_FILE"
  [[ -n "$newstate" ]] && printf '%s\n' "$newstate" > "$CC_STATE"
  if printf '%s\n' "$rest" > "$CC_CARD.tmp.$$" 2>/dev/null; then mv -f "$CC_CARD.tmp.$$" "$CC_CARD"; else rm -f "$CC_CARD.tmp.$$"; fi
  return 0
}

# Trim the rolling trail (called off the hot path: PreCompact/SessionStart/Stop).
cc_trail_rotate() {
  [[ -s "$CC_TRAIL" ]] || return 0
  local n; n="$(wc -l < "$CC_TRAIL" 2>/dev/null || echo 0)"; n="${n// /}"
  if [[ "$n" -gt "$CC_LOG_TRIM_AT" ]]; then
    tail -n "$CC_LOG_KEEP" "$CC_TRAIL" > "$CC_TRAIL.tmp.$$" 2>/dev/null && mv -f "$CC_TRAIL.tmp.$$" "$CC_TRAIL"
  fi
}

# Number of trail entries newer than the last compaction (all, if never).
cc_count_since_compact() {
  [[ -s "$CC_TRAIL" ]] || { echo 0; return 0; }
  local since; since="$(cc_state_get compacted_at)"
  if [[ -z "$since" ]]; then local n; n="$(wc -l < "$CC_TRAIL")"; echo "${n// /}"; return 0; fi
  jq -rs --arg s "$since" 'map(select(.ts > $s)) | length' "$CC_TRAIL" 2>/dev/null || echo 0
}

# Epoch seconds for an ISO "YYYY-MM-DDTHH:MM:SSZ" string ("" on failure).
cc_epoch() {
  date -u -d "$1" +%s 2>/dev/null || date -u -j -f '%Y-%m-%dT%H:%M:%SZ' "$1" +%s 2>/dev/null || echo ""
}

# Minutes since refreshed_at; "" when never refreshed.
cc_drift_minutes() {
  local r t0 now; r="$(cc_state_get refreshed_at)"
  [[ -n "$r" ]] || { echo ""; return 0; }
  t0="$(cc_epoch "$r")"; [[ -n "$t0" ]] || { echo ""; return 0; }
  now="$(date -u +%s)"
  echo $(( (now - t0) / 60 ))
}

# Emit {"hookSpecificOutput":{"hookEventName":<ev>,"additionalContext":<text>}}
cc_emit_context() {  # <event> <text>
  jq -nc --arg ev "$1" --arg ctx "$2" '{hookSpecificOutput:{hookEventName:$ev,additionalContext:$ctx}}'
}
