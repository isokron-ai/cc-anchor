}

# cc_log MSG — append "<iso> MSG" to the runtime log (never stdout).
cc_log() { cc_ensure_dirs || return 0; local n; cc_now_var n; printf '%s %s\n' "$n" "$*" >> "$CC_LOG" 2>/dev/null || true; }

# cc_log_once KEY MSG — log at most once per hour per key (latch file mtime).
cc_log_once() {
  local key="$1"; shift
  local d="$CC_RUN/once" f
  f="$d/$key"
